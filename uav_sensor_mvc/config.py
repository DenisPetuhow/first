THREAT_LOOKAHEAD_POWER = 3.0

# --- Построение маршрутов вход→цель по весовой карте (вкладка 3) ---
# Маршруты строятся СТОХАСТИЧЕСКИМ блужданием по коридорам (model/threat_routes.py),
# а НЕ поиском минимальной стоимости. Прежние константы стоимости прохода
