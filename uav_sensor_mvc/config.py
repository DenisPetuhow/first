                                     # этот запас и уходит на боковой разброс маршрутов)

# ПРОФИЛЬ РАСХОДА ЗАПАСА ХОДА. На каждом шаге известен «свободный запас»:
#   slack = (остаток хода) − (кратчайший путь до цели отсюда)
# Это километры, которые ещё можно потратить на виляние. Профиль решает, КОГДА их тратить:
#   late  — пока запас есть, маршрут свободно виляет по коридорам; когда запас тает —
#           выпрямляется и идёт к цели (БПЛА на исходе топлива не петляет);
#   early — наоборот: сначала идёт кратчайшим путём, накопленный запас тратит на виляние
#           ближе к цели;
#   even  — тратит запас равномерно на всём пути.
# Без этого маршрут летел «вслепую», проедал весь запас на виляние и отбраковывался у самой
# цели: на реальных данных доходило лишь ~5 % попыток (см. ЖУРНАЛ_ПРОЕКТА, п. 41).
THREAT_SPEND_LABELS = {
    "late":  "виляет, потом прямо",
    "early": "прямо, потом виляет",
    "even":  "равномерно",
}
# Режимы = ПРИОРИТЕТ выбора следующей клетки по ВЕСУ сетки (тепловой карты). Боковой
# РАЗБРОС маршрутов по карте — отдельно, случайный на каждый маршрут (не зависит от
# режима), поэтому пути покрывают всю карту в любом режиме.
