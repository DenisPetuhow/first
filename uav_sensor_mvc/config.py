# мостики через провалы ≤ разрыва; главное ограничение — запас хода L_max (полная
# длина пути вход→ячейка→цель ≤ L_max). Провал больше разрыва — коридор порван.
# ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ для Params.threat_max_gap_km (сам параметр задаётся в интерфейсе,
