# -*- coding: utf-8 -*-
"""
Конфигурация модели размещения датчиков обнаружения БПЛА.

Содержит:
  * Params       — все входные параметры (редактируемые в интерфейсе);
  * MODES        — три режима оптимизации через веса (alpha1, alpha2);
  * MODE_LABELS  — русские подписи режимов;
  * TRAJ_LABELS  — подписи моделей движения (этап 1 — дуги, этап 2 — петли);
  * THEME        — единая цветовая тема интерфейса.

Геометрия задаётся двумя числами: расстоянием |AB| и запасом хода L_max.
Точки A, B размещаются симметрично на оси X; карта (оси) масштабируется
автоматически под эллипс достижимости. Для гео-режима A, B можно задать
в долготе/широте (см. model.geometry.geo_to_local_km).
"""
from dataclasses import dataclass
from typing import Tuple


# ----------------------------------------------------------------------
# Три режима оптимизации: веса (alpha1 — кратность, alpha2 — равномерность)
# ----------------------------------------------------------------------
MODES = {
    "distribution": (0.25, 0.75),   # акцент на равномерное распределение
    "crossing":     (0.75, 0.25),   # акцент на кратность пересечений
    "balanced":     (0.50, 0.50),   # сбалансированный
}

MODE_LABELS = {
    "distribution": "распределение",
    "crossing":     "пересечение",
    "balanced":     "сбалансированный",
}

TRAJ_LABELS = {
    "arc":        "дуги (этап 1)",
    "serpentine": "петли (этап 2)",
}

# Малый вес вторичного критерия «распределения» (см. optimization.greedy):
# включается, когда основной субмодулярный критерий насыщается, и гарантирует,
# что задействованы ВСЕ N датчиков, разнесённые по плотности маршрутов.
SPREAD_EPS = 1.0


# ----------------------------------------------------------------------
# Цветовая тема интерфейса
# ----------------------------------------------------------------------
THEME = {
    "bg":          "#0f1623",   # фон фигуры
    "panel":       "#172033",   # фон панели управления
    "axes":        "#0c1320",   # фон сцены
    "accent":      "#36c5f0",   # акцент (голубой)
    "accent2":     "#7c5cff",   # акцент 2 (фиолетовый)
    "ok":          "#3ddc97",   # зелёный (датчики, успех)
    "warn":        "#ff5d6c",   # красный (БПЛА, экстремум)
    "text":        "#e6edf3",   # основной текст
    "muted":       "#8aa0b6",   # приглушённый текст
    "grid":        "#22304a",   # сетка
    "ellipse":     "#5b6b85",   # контур эллипса
}


@dataclass
class Params:
    """Входные параметры модели (все редактируются в интерфейсе)."""
    ab_distance: float = 100.0     # расстояние между A и B, км
    L_max: float = 150.0           # запас хода (предельная длина траектории), км
    N: int = 6                     # число датчиков (все задействуются)
    R: float = 12.0                # радиус обнаружения датчика, км
    k: int = 3                     # требуемая кратность обнаружения
    L_seg: int = 10                # число сегментов разбиения маршрута
    angle_step_deg: float = 10.0   # шаг угла отклонения для веера вероятных дуг
    mode: str = "balanced"         # режим оптимизации
    traj_model: str = "arc"        # модель движения
    T: int = 400                   # число итераций накопления выборки
    grid_step: float = 8.0         # шаг сетки кандидатных позиций, км
    sigma_frac: float = 0.45       # ширина пучка (доля предельного угла)
    n_points: int = 140            # число точек дискретизации маршрута
    seed: int = 1                  # зерно ГСЧ

    # геопривязка (опционально, задаётся из CLI)
    geo: bool = False
    A_geo: Tuple[float, float] = (0.0, 0.0)   # (широта, долгота) точки A
    B_geo: Tuple[float, float] = (0.0, 0.0)   # (широта, долгота) точки B

    @property
    def A(self) -> Tuple[float, float]:
        return (0.0, 0.0)

    @property
    def B(self) -> Tuple[float, float]:
        return (float(self.ab_distance), 0.0)

    def validate(self) -> None:
        if self.L_max <= self.ab_distance:
            raise ValueError(
                f"Запас хода L_max={self.L_max} должен быть больше |AB|="
                f"{self.ab_distance}: иначе траектория невозможна.")
        if self.mode not in MODES:
            raise ValueError(f"Неизвестный режим: {self.mode}")
        if self.traj_model not in TRAJ_LABELS:
            raise ValueError(f"Неизвестная модель движения: {self.traj_model}")
        if not (1 <= self.L_seg <= 31):
            raise ValueError("L_seg должно быть в диапазоне 1..31.")
        if self.N < 1 or self.k < 1 or self.R <= 0:
            raise ValueError("N, k должны быть >= 1, R > 0.")
        if self.angle_step_deg < 1.0:
            raise ValueError("Шаг угла должен быть >= 1 градуса.")
