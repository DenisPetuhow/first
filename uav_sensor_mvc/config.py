# --- ПРЕДВИДЕНИЕ ПРЕПЯТСТВИЯ (обход холма) ---
# Горизонт решения в блуждании был 500 м — одна ячейка: узкий холм маршрут обтекал, а
# перед широким массивом упирался, потому что тяга к цели считается по чистой геометрии.
# Теперь при выборе соседа учитывается средний рельеф ВПЕРЕДИ по этому направлению.
# ─── ТЯГА К ЦЕЛИ: ПО СТОИМОСТИ, А НЕ ПО КИЛОМЕТРАМ ────────────────────────────────
# Поле расстояний, по которому маршрут спускается к цели, считалось ЧИСТО ГЕОМЕТРИЧЕСКИ:
# `_dijkstra_dist` не заглядывал в вес ни разу. Вес входил только в выбор соседней клетки,
# слабым множителем. Замер размахов в оценке соседа:
#     приближение к цели  exp(prog/tau)  ×44 … ×10^13
#     удержание курса     hf             ×280
#     ВЕС клетки          corr           ×17
# Иерархия «геометрия ≫ курс ≫ вес» — отсюда маршруты, идущие верхней дорогой мимо
# тяжёлого коридора, и линии через пустошь у заповедника.
#
# Теперь тяга считается по СТОИМОСТИ. Цена шага = его длина × ДВА множителя:
#     mul = (1 + THREAT_COST_POWER · (1 − вес))  ×  (1 + THREAT_COST_RELIEF · (1 − рельеф))
# оба сомножителя в [1, 1+сила], поэтому поле остаётся в КИЛОМЕТРАХ-эквивалентах:
# «сто́ит как N км пути». Благодаря этому «температура» tau и пороги сохраняют смысл.
#
# ПОЧЕМУ ДВА МНОЖИТЕЛЯ, А НЕ ОДИН. Сперва привлекательность считалась как ПРОИЗВЕДЕНИЕ
# «вес × множитель рельефа», обрезанное единицей, — и обрезка съедала всё поощрение за
# низину: река в пойме (вес 1.0, рельеф 1.4) давала 1.4 → обрезалось до 1.0, ровно
# столько же, сколько у той же реки на голом плато. Рельеф работал только как ослабление
# веса, хотя это НЕЗАВИСИМАЯ физика: вес отвечает за «где есть ориентиры», рельеф — за
# «где меня видно». Разведённые множители дают правильную картину: при равном весе низина
# дешевле гребня, а голая низина остаётся дорогой (ориентиров нет), но дешевле голого
# гребня. Побочно чинится и «бесплатный перелёт» через возвышенность: ячейки мостика на
# гребне теперь дорогие, и маршрут выбирает либо обход, либо перелёт в низком месте.
# 0.0 у обоих -> в точности прежнее поведение (чистая геометрия).
#
# ПОЧЕМУ 1.0, А НЕ БОЛЬШЕ (замер, 250 линий в реальном показе):
#   сила   вес под линией   точек по пустым   покрытие области линиями
#   0.0        11.76             35.4 %              46.7 %
#   1.0        20.18             13.8 %              28.2 %
#   2.0        21.68             11.2 %              19.7 %
#   3.0        23.26              9.1 %              15.0 %
# Дальше единицы вес растёт слабо, а РАЗБРОС линий падает быстро: маршруты сходятся на
# одних и тех же лучших коридорах. Полную картину «куда вообще можно долететь» даёт
# закрашенная область (она от силы не зависит вовсе), но сами линии должны оставаться
# представительными, а не сливаться в один путь. 1.0 берёт почти весь выигрыш по весу,
# теряя вдвое меньше разброса.
THREAT_COST_POWER = 1.0
# СИЛА РЕЛЬЕФА В ЦЕНЕ ПРОХОДА. Множитель рельефа k нормируется по своему диапазону
# [THREAT_DEM_K_MIN, THREAT_DEM_K_MAX] -> 0 (гребень) … 1 (низина-укрытие), поэтому
# параметр не зависит от того, как настроены сами пороги высот.
# Работает, только когда рельеф добавлен в карту кнопкой; 0.0 -> высота на цену не влияет.
THREAT_COST_RELIEF = 1.0
# РАЗНООБРАЗИЕ ВЫБОРКИ. Одного стоимостного поля мало: если путь A дешевле пути B на
# десятки единиц, локальная стохастика туда не уведёт — разница копится по всей длине,
# и ВСЕ маршруты сваливаются в один оптимум (замер: 250 линий слились в одну полосу,
# покрытие области упало с 47 до 26 %, коридоры вокруг пустовали).
# Поэтому считается НЕСКОЛЬКО полей с разной «жадностью» a, и каждому маршруту достаётся
# своё: a≈1 жмётся к коридорам и низинам, a≈0 летит напрямик, большинство — между.
# Физически это разные повадки, а не «два режима»: выборка показывает их СРАЗУ.
#
# Поля именно ПРЕДРАССЧИТЫВАЮТСЯ, каждое своей Дейкстрой по множителю `1 + a·(mul − 1)`,
# а не смешиваются линейно: смесь двух готовых полей расстояний полем расстояний НЕ
# является — там, где по километрам выгодно влево, а по стоимости вправо, у смеси
# появляется локальный минимум-ловушка, спуск застревает и маршрут не доходит
# (замер: набиралось 128 итераций из 150 вместо 150).
THREAT_COST_MIX_STEPS = (0.0, 0.35, 0.7, 1.0)
#
# Смещение задаётся показателем: a = U(0,1) ** THREAT_COST_MIX_BIAS. Меньше единицы —
# сдвиг К СТОИМОСТИ (больше маршрутов по коридорам), больше — к геометрии.
# 0.0 -> все a = 1, смешивание выключено (то самое зацикливание).
#
# ПОДБОР (250 линий, режим «приоритет макс. веса», рельеф включён):
#   вариант                  вес   по возвышенностям   покрытие области
#   чистая геометрия       12.03         28.0 %             46.4 %
#   стоимость без смеси    20.09         10.0 %             25.6 %   <- зацикливание
#   bias 0.3               18.73         11.4 %             30.2 %
#   bias 0.5               17.12         13.4 %             36.2 %
#   bias 0.8               15.60         17.1 %             41.8 %   <- принято
#   bias 1.5               13.80         21.9 %             44.7 %
# 0.8 возвращает 90 % прежнего разброса, удерживая вес на 30 % выше геометрии и вдвое
# сокращая долю пути по возвышенностям. Цель заказчика — «в приоритете маршруты по
# низине, но не зацикливаться»: основная масса идёт по рельефу и весам, а выборка
# по-прежнему покрывает остальные возможные пути.
THREAT_COST_MIX_BIAS = 0.8
# ЗАПАС ХОДА СЧИТАЕТСЯ ОТДЕЛЬНО, по честным километрам: физику подменять нельзя.
# Маршрут спускается по стоимостному полю, но «хватит ли хода», отбраковка и slack —
# всё по геометрическому. Поэтому полей ДВА.
#
# РАЗМАХ ПРИОРИТЕТА ПО ВЕСУ при выборе соседней клетки (`_mode_corridor_pref`).
# Стоимость выше задаёт СТРАТЕГИЮ — куда идти вообще; это — ТАКТИКУ: какую из соседних
# клеток взять. Предпочтение соседа = 0.10 + GAIN · вес(0…1), то есть размах
# (0.10+GAIN)/0.10. Было 1.6, то есть ×17 — на фоне удержания курса (×280) и приближения
# к цели (до ×10^13) это почти не влияло.
# Замер (150 маршрутов, режим «приоритет макс. веса»):
#   БЕЗ стоимости:  ×17 -> вес 11.60;  ×41 -> 11.59;  ×101 -> 11.64   (не влияет вовсе)
#   СО стоимостью:  ×17 -> вес 20.60;  ×41 -> 22.53;  ×101 -> 22.19
#   доходимость при этом 55 % -> 51 % -> 40 %
# Отсюда 4.0 (×41): прирост +9.4 % к весу и −3 п.п. точек по пустым ячейкам, дальше вес
# уже падает, а доходимость рушится. Само по себе, без стоимости, усиление бесполезно —
# это и есть подтверждение того, что вес тонул в геометрии.
# 1.6 -> прежнее поведение в точности.
THREAT_WEIGHT_GAIN = 4.0

THREAT_LOOKAHEAD_KM = 2.0            # как далеко маршрут смотрит вперёд
# Сила влияния; 0 = выключено (маршруты ровно как раньше). Значение было 1.5 «на глаз»,
# теперь подобрано замером (150 маршрутов, режим «приоритет макс. веса»):
