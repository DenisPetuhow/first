# СТРОГИЙ ПОДЪЁМ: чтобы попасть в класс выше, мало дотянуться до его минимума — надо
# превзойти МАКСИМУМ своего класса (чтобы стать городом, надо быть больше всех посёлков).
# Классы по тегу перекрываются почти полностью (city 0.50…42.75 км² против town
# 0.25…23.50), и без этого «дотянуться до минимума city» может рядовая деревня.
# Асимметрия намеренная: вверх пройти трудно, вниз легко — убираем мы ЛОЖНЫЕ города.
THREAT_PLACE_GRADE_STRICT_UP = True
# Если в классе меньше стольких пунктов, статистика по нему ничего не значит — и В ЭТОТ
