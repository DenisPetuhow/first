    L_seg: int = 10                # число сегментов разбиения маршрута
    angle_step_deg: float = 10.0   # шаг угла веера вероятных дуг
    corridor_depth: float = 60.0   # глубина зоны старта (вдоль A->B), вкладка 2
    corridor_width: float = 120.0  # ширина зоны старта (поперёк A->B), вкладка 2
    speed_kmh: float = 180.0       # крейсерская скорость БПЛА, км/ч (типично для коммерческих самолётного типа)
    bank_deg: float = 25.0         # макс. угол крена, ° (-> радиус разворота R_min)
    n_min: int = 2                 # мин. число путевых точек маршрута (задаёт пользователь)
    n_max: int = 5                 # макс. число путевых точек (рандом в [n_min, n_max])
    maneuver_law: str = "points"   # закон манёвра: "points" (по точкам) | "sine" (по синусу)
    waypoint_zone: str = "inside"  # точки маршрута: "inside" (в зоне старта, полный разброс) | "outside" (только за зоной)
    map_layer: str = "scheme"      # подложка карты (вкладка 2): scheme/osm/topo/satellite/dark
    map_offline: bool = False      # True -> карта читает ТОЛЬКО кэш, сеть не запрашивается
    # --- вкладка 3 (цифровая карта угроз) ---
    threat_N: int = 12             # число датчиков на весовой карте
    threat_R: float = 12.0         # радиус обнаружения датчика, км
    threat_k: int = 3              # кратность насыщения (веса клеток на карте угроз)
    threat_cand_step_km: float = 3.0   # шаг сетки кандидатных позиций датчика, км
    threat_min_sep_frac: float = 0.75  # мин. разнос датчиков (доля R) — распределённость
    threat_exclude_water: bool = True  # датчики НЕ ставятся на воду (запрет спавна)
    # входные данные маршрута (окно «Входные данные», вкладка 3):
    threat_L_max: float = 200.0    # запас хода БПЛА, км (главное ограничение маршрута)
    threat_speed_kmh: float = 180.0    # крейсерская скорость, км/ч (для R_min)
    threat_bank_deg: float = 25.0  # макс. крен, ° (для радиуса разворота R_min)
    threat_turn_interval_km: float = 8.0  # целевая длина ПРЯМОГО участка, км (к ней стремится маршрут)
    threat_max_gap_km: float = THREAT_MAX_GAP_KM  # РАЗРЫВ между весовыми секторами, км:
                                   # пустое место короче этого БПЛА перелетит (коридоры
                                   # сшиваются), длиннее — коридор разорван и маршрута нет.
                                   # Меняет и область залёта, и набор возможных маршрутов.
    threat_spend: str = "late"     # профиль расхода запаса хода (THREAT_SPEND_LABELS)
    threat_L_max_manual: bool = False  # False -> запас хода авто (|AB|+25%); True -> задан руками
    threat_iter_mode: str = "mix"  # приоритет выбора клетки по ВЕСУ (THREAT_ITER_MODE_LABELS)
    threat_iter_spread: str = "mix"  # РАЗБРОС маршрута по карте (THREAT_ITER_SPREAD_LABELS)
    threat_iter_routes: int = 150  # число итераций T (сколько маршрутов сгенерировать)
    threat_iter_gen_frac: float = 0.10  # доля обобщённой выборки (0.10 = 10% пройденных итераций)
    map_layer3: str = "osm"        # подложка карты (вкладка 3)
    map_offline3: bool = False     # офлайн-режим подложки (вкладка 3)
    mode: str = "balanced"         # режим оптимизации
    traj_model: str = "arc"        # модель движения
    motion_profile: str = "mixed"  # профиль разброса маршрутов
    T: int = 400                   # число итераций накопления
    grid_step: float = 7.0         # шаг сетки кандидатных позиций, км
    sigma_frac: float = 0.45       # ширина пучка (доля предельного угла)
    n_points: int = 140            # точек дискретизации маршрута
    seed: Optional[int] = None     # зерно ГСЧ; None -> случайно при каждом прогоне

    # геопривязка (опционально, из CLI)
    geo: bool = False
    A_geo: Tuple[float, float] = (0.0, 0.0)
    B_geo: Tuple[float, float] = (0.0, 0.0)

    @property
    def A(self) -> Tuple[float, float]:
        return (0.0, 0.0)

    @property
    def B(self) -> Tuple[float, float]:
        return (float(self.ab_distance), 0.0)

    def validate(self) -> None:
        if self.L_max <= self.ab_distance:
            raise ValueError(
                f"Запас хода L_max={self.L_max} должен быть больше |AB|="
                f"{self.ab_distance}.")
        if self.mode not in MODES:
            raise ValueError(f"Неизвестный режим: {self.mode}")
        if self.traj_model not in TRAJ_LABELS:
            raise ValueError(f"Неизвестная модель движения: {self.traj_model}")
        if self.motion_profile not in MOTION_PROFILES:
            raise ValueError(f"Неизвестный профиль: {self.motion_profile}")
        if not (1 <= self.L_seg <= 31):
            raise ValueError("L_seg должно быть 1..31.")
        if self.N < 1 or self.k < 1 or self.R <= 0:
            raise ValueError("N, k >= 1, R > 0.")
        if self.angle_step_deg < 1.0:
            raise ValueError("Шаг угла >= 1°.")
