#   1.5   13.72         19.4 %              85.6 м               33.0 %
#   3.0   14.88         17.1 %              82.7 м               32.8 %
# При 3.0 лучше ПО ВСЕМ метрикам сразу — и вес выше, и высота ниже, — а разброс теряет
