# «Возможные маршруты», показываемые ДО итераций. Это ВЫБОРКА: всего маршрутов вход→цель
# порядка 1e107 (точное число считает ThreatModel.count_routes: путь — 167 шагов по сетке,
# на каждом ~3 развилки, итого 3^167). Перечислить их нельзя — атомов во Вселенной ~1e80.
# Полную картину «где может пролететь БПЛА» даёт ЗАКРАШЕННАЯ ОБЛАСТЬ (она точна), а эти
# линии — представительные примеры, разложенные по области КАК МОЖНО ШИРЕ (жадный отбор по
# покрытию, см. ThreatModel._spread_over_area).
THREAT_ROUTE_COUNT = 250             # сколько маршрутов ПОКАЗАТЬ (отобрать из пула)
THREAT_ROUTE_POOL_MULT = 2           # пул кандидатов = COUNT × это (из него идёт жадный отбор).
                                     # Больше пул -> шире покрытие области, но дольше счёт;
                                     # на реальных данных покрытие насыщается (замер, 250 линий):
                                     #   ×1 -> 48 % области за 3 c;   ×2 -> 54 % за 8 c;
                                     #   ×3 -> 57 % за 12 c;          ×4 -> 58 % за 16 c.
                                     # ×2 — баланс: дальше растёт цена, а не покрытие.
# ЦЕННОСТЬ ЯЧЕЙКИ при жадном отборе «возможных маршрутов». Отбор максимизировал ГОЛОЕ
