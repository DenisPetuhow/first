# Медиана и MAD сами не сдвигаются от выбросов, поэтому порог задаётся ОДИН РАЗ в
# безразмерных единицах и работает на любом участке — хоть в степи, хоть в промрайоне.
# Абсолютные километры сюда не входят, подгонки под конкретную область нет.
