#   "none"    — БЕЗ отсева, границы по всей выборке класса (значение по умолчанию);
#   "mad"     — внутриклассовый: далеко ли объект от середины СВОЕГО класса
#               (modified z-score, порог THREAT_PLACE_GRADE_OUTLIER);
#   "cascade" — межклассовый, снизу вверх: «город не может быть меньше самого крупного
#               посёлка» — village задаёт планку для town, очищенный town для city;
#   "both"    — сперва MAD, затем каскад.
#
# ПОЧЕМУ ПО УМОЛЧАНИЮ ОТСЕВА НЕТ (замер, участок Северодонецк → Луганск):
#   режим     вверх  вниз   город  коридоров
#   none          0    72    3395      11140   <- лучший
#   mad          12    49    3417      11120
#   cascade       0    72    3395      11140   <- ровно как none
#   both         12    49    3417      11120
# Отсев РАБОТАЕТ ПРОТИВ строгого подъёма (THREAT_PLACE_GRADE_STRICT_UP). Порог подъёма
# берётся как МАКСИМУМ своего класса; отсев выбрасывает крупные пункты как «выбросы» и
# сбивает этот максимум вниз — планка town→city падает с 23.50 до 6.25 км², и подняться
# становится легко. Без отсева ложных подъёмов ноль.
# Каскад совпал с «none» не случайно: он отбрасывает МЕЛКИЕ пункты, то есть поднимает
# МИНИМУМ класса, а порог подъёма использует МАКСИМУМ класса снизу — разные концы
# распределения. Сама мысль «город не может быть меньше максимума посёлков» полностью
# воплощена в строгом подъёме, только применена в нужный момент: не при чистке выборки,
# а при решении о переводе. Режимы оставлены для другого участка, где картина может
# отличаться. Подробности — МЕТОДИЧКА_КАРТА_УГРОЗ.md §13.0г.
