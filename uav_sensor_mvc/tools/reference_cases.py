                got, fixed, moved = run_case(m, c)
                results[key].append(got)
                holds[key].append([(round(x, 6), round(y, 6)) for x, y, _ in fixed])
                print("      случай %-3s %-43s %s"
                      % (c["key"], c["title"],
                         "малых %d, больших %d" % (got["малых"], got["больших"])))
                # ИНВАРИАНТЫ — проверяются в каждом прогоне, эталон для них не нужен
