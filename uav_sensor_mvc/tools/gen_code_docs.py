def src(obj, start=None, end=None):
    """Исходник функции/класса или его кусок блоком кода. Вход: объект, строки-маркеры начала и конца (без учёта
    отступа). Отдаёт: текст Markdown."""
    t = textwrap.dedent(inspect.getsource(obj))  # исходник без общего отступа
    if start:                                    # нужен кусок — отрезать до строки с маркером
        a = t.index(start.strip()); a = t.rfind("\n", 0, a) + 1; t = t[a:]   # начало строки маркера
