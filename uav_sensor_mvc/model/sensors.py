# -*- coding: utf-8 -*-
"""
ТИПЫ ДАТЧИКОВ И ДАТЧИКИ, ЗАДАННЫЕ ЧЕЛОВЕКОМ (задача 8.7).

Здесь живут две вещи, которых раньше в модели не было:

* **четыре типа датчиков** вместо двух. Типы 1–3 — малые (сеть по маршрутам), тип 4 —
  большие (круговой щит у цели). У каждого своё число, свой радиус и своя кратность;
* **датчик, поставленный человеком** — с типом и режимом (динамический / статический).

⚠️ ПОЧЕМУ ЗДЕСЬ НЕТ СВОИХ ЧИСЕЛ. Значения параметров — только в `config.Params`, это
правило проекта. Модуль ничего не хранит: он лишь СОБИРАЕТ разрозненные поля `Params`
(`threat_N`, `threat_R2`, …) в удобный список `SensorSpec` и разбирает их обратно.
Единственный источник истины — по-прежнему `Params`.

⚠️ ПОЧЕМУ СТАРЫЕ ИМЕНА ОСТАЛИСЬ. `threat_N`, `threat_R`, `threat_k`, `threat_N_big`,
`threat_R_big` читаются в десятке мест (расстановка, показатели, автошаг сетки, эталон,
окна интерфейса) — переименование расползлось бы по всему проекту ради косметики.
Поэтому тип 1 и тип 4 — это ровно они, а новыми полями заведены только типы 2 и 3.
Соответствие: тип 1 ← `threat_N`/`threat_R`, тип 2 ← `threat_N2`/`threat_R2`,
тип 3 ← `threat_N3`/`threat_R3`, тип 4 ← `threat_N_big`/`threat_R_big`.
"""
from dataclasses import dataclass

SMALL_TYPES = (1, 2, 3)        # малые: сеть по маршрутам, общий CoverageCache
BIG_TYPE = 4                   # большие: круговой щит у цели, своё правило (кольцо)
TYPE_IDS = SMALL_TYPES + (BIG_TYPE,)

# Поля Params, отвечающие за каждый тип: (число, радиус, кратность).
# Кратность типа 4 отдельным полем НЕ заведена: большие ставятся кольцом по УГЛУ, и
# кратность в их расстановке не участвует — параметр, который никто не читает, только
# сбивал бы с толку (его же поймал бы check_dead_code.py). В окне поле у типа 4
# показывается общим, из threat_k.
_FIELDS = {
    1: ("threat_N",     "threat_R",     "threat_k"),
    2: ("threat_N2",    "threat_R2",    "threat_k2"),
    3: ("threat_N3",    "threat_R3",    "threat_k3"),
    4: ("threat_N_big", "threat_R_big", "threat_k"),
}

KIND_LABEL = {"small": "малый", "big": "большой"}


@dataclass
class SensorSpec:
    """Параметры ОДНОГО типа датчиков: сколько, какого радиуса, с какой кратностью."""
    type_id: int
    n: int
    r_km: float
    k: int
    kind: str                  # "small" (типы 1–3) | "big" (тип 4)

    @property
    def active(self):
        """Тип участвует в расстановке. Пустой тип (N = 0) — не ошибка, а «не нужен»:
        так заказчик выключает лишние типы, не удаляя их настройки."""
        return int(self.n) > 0 and float(self.r_km) > 0.0

    @property
    def label(self):
        return "Тип %d · %s" % (self.type_id, KIND_LABEL.get(self.kind, self.kind))


@dataclass
class ManualSensor:
    """Датчик, ЗАДАННЫЙ ЧЕЛОВЕКОМ: мышью по карте, строкой в таблице или из файла.

    ⚠️ Координаты — в КИЛОМЕТРАХ рабочего фрейма, как и всё остальное в модели. В файл
    они пишутся в градусах (формат 8.7.7): градусы самодостаточны и переносятся между
    участками, а километры зависят от якоря области.

    `static=True` — позиция не меняется НИ ПРИ КАКИХ УСЛОВИЯХ: алгоритм принимает её как
    данность и достраивает остальные датчики вокруг. `static=False` — датчик обычный,
    его позицию выбирает жадный алгоритм (запись в таблице тогда лишь задаёт тип)."""
    type_id: int
    static: bool
    x_km: float
    y_km: float


def _num(p, name, default=0):
    """Прочитать поле Params, пережив его отсутствие (старые сохранённые настройки)."""
    return getattr(p, name, default)


def sensor_types(p):
    """Все четыре типа списком, в порядке 1, 2, 3, 4 — собраны из полей `Params`.

    ⚠️ КРАТНОСТЬ ЗАВИСИТ ОТ ПЕРЕКЛЮЧАТЕЛЯ `threat_k_same`. «Одна на всех» (умолчание) —
    у каждого типа берётся общая `threat_k`; «у каждого своя» — собственное поле типа.
    Дублирование сделано ЗДЕСЬ, а не при расчёте: в окне человек обязан видеть в полях
    то самое число, с которым программа будет считать."""
    same = bool(_num(p, "threat_k_same", True))
    k_all = int(_num(p, "threat_k", 3) or 1)
    out = []
    for tid in TYPE_IDS:
        f_n, f_r, f_k = _FIELDS[tid]
        k = k_all if same else int(_num(p, f_k, k_all) or 1)
        out.append(SensorSpec(
            type_id=tid,
            n=int(_num(p, f_n, 0) or 0),
            r_km=float(_num(p, f_r, 0.0) or 0.0),
            k=max(1, k),
            kind="big" if tid == BIG_TYPE else "small"))
    return out


def active_small(p):
    """Малые типы, которые реально нужно ставить (N > 0)."""
    return [s for s in sensor_types(p) if s.kind == "small" and s.active]


def min_small_radius(p):
    """Наименьший радиус среди РАБОТАЮЩИХ малых типов — по нему берётся шаг сетки
    кандидатов.

    ⚠️ Именно по минимальному, а не по первому и не по среднему: шаг крупнее зоны обзора
    оставляет между кандидатами дыру шире, чем видит датчик, и лучшая позиция становится
    недоступна. Замер (R = 2 км, 5 датчиков, 150 маршрутов): шаг 0.5 км — засечка 96.7 %,
    3 км — 82.7 %, 6 км — 17.3 %. Грубый шаг бьёт по САМОМУ МЕЛКОМУ типу, поэтому
    равняемся на него.

    Нет ни одного работающего малого типа — возвращается радиус типа 1: расстановки всё
    равно не будет, а звать функцию с пустым результатом неудобно."""
    act = active_small(p)
    if act:
        return min(float(s.r_km) for s in act)
    return float(_num(p, "threat_R", 2.0) or 2.0)


def format_types_header(p):
    """Шапка файла датчиков — таблица типов (формат 8.7.7). Возвращает список строк
    БЕЗ знака `#`: его добавляет тот, кто пишет файл."""
    rows = ["типы датчиков:",
            "  тип  класс    N   R, км   кратность k"]
    for s in sensor_types(p):
        rows.append("  %3d  %-7s %3d  %6.1f  %6d"
                    % (s.type_id, KIND_LABEL.get(s.kind, s.kind), s.n, s.r_km, s.k))
    return rows
