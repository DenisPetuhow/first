# -*- coding: utf-8 -*-
"""
MODEL · КООРДИНАТНЫЙ ФРЕЙМ: единственное место, где градусы переводятся в километры.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Один и тот же перевод жил ДВАЖДЫ: в `model/threat_grid.py`
(для расчёта) и в `view_qt/geomap.py` (для показа). Формулы совпадали, но ничто этого не
гарантировало: правка в одном месте не доходила до другого, и расхождение проявилось бы
не ошибкой, а тихим сдвигом карты относительно данных. Теперь формула одна, а те два
модуля её импортируют (план 8, задача 8.3).

ЧТО ЭТО ЗА ПРОЕКЦИЯ. Локальная равнопромежуточная (equirectangular) с масштабом на
опорной широте:

    x_км = (lon − lon0) · 111.32 · cos(lat0)
    y_км = (lat − lat0) · 111.32

Она верна по расстояниям локально и тем точнее, чем меньше район.

⚠️ ПРЕДЕЛ РАЙОНА. Тайлы подложки нарисованы в Web Mercator, и её привязывают по углам;
внутри картинки расхождение с нашей проекцией растёт к середине: **117 м** на участке
55 км по широте, **2.5 км** на 255 км, **43 км** на 1035 км. Поэтому район расчёта
держат не шире ~150 км ([план 8 §0.4](../теория/планы/8_ПЛАН_КАРТА_И_ИНТЕРФЕЙС.md)).

ЯКОРЬ — юго-западный угол района: обе координаты положительные, от 0 до размера участка
(ОГРАНИЧЕНИЯ 5.1г). ⚠️ При смене якоря кэш слоёв `.npz` обязателен к пересборке: там
лежат уже посчитанные километры.

Модуль намеренно БЕЗ зависимостей от `config` и Qt — только stdlib и numpy, чтобы его
мог импортировать и `view_qt/geomap.py`, который от `config` не зависит принципиально.
"""
import math

import numpy as np

# Длина градуса ШИРОТЫ почти постоянна (меридиан делится на 360°), длина градуса
# ДОЛГОТЫ убывает к полюсам как cos(широты) — меридианы сходятся.
#
# ⚠️ ДВА РАЗНЫХ КОЭФФИЦИЕНТА — ЭТО НЕ ОПЕЧАТКА, А ДЕЙСТВУЮЩЕЕ ПОВЕДЕНИЕ ПРОЕКТА.
# Для широты взято 110.574 (длина градуса меридиана на экваторе, WGS84), для долготы —
# 111.320·cos(широты). Физически согласованнее было бы одно среднее значение, но менять
# его НЕЛЬЗЯ: этими коэффициентами посчитаны километры внутри кэшей `.npz` и все числа
# эталона (ОГРАНИЧЕНИЯ §6). Замена 110.574 на 111.320 сдвинула бы карту на 0.37 км при
# высоте участка 55 км — тихо, без единой ошибки. Обе прежние копии формулы (в
# `threat_grid.py` и `geomap.py`) использовали именно эти числа; проверено 04.09.2026.
KM_PER_DEG_LAT = 110.574
KM_PER_DEG_LON_EQ = 111.320


def km_per_deg_lon(lat0):
    """Км в одном градусе ДОЛГОТЫ на широте lat0."""
    return KM_PER_DEG_LON_EQ * math.cos(math.radians(lat0))


def lonlat_to_km(lon, lat, lon0, lat0):
    """(долгота, широта) → (x, y) в км от опорной точки. Скаляры и массивы numpy."""
    return ((np.asarray(lon, float) - lon0) * km_per_deg_lon(lat0),
            (np.asarray(lat, float) - lat0) * KM_PER_DEG_LAT)


def km_to_lonlat(x_km, y_km, lon0, lat0):
    """Обратное преобразование: км → (долгота, широта)."""
    return (lon0 + np.asarray(x_km, float) / km_per_deg_lon(lat0),
            lat0 + np.asarray(y_km, float) / KM_PER_DEG_LAT)


def bbox_lonlat_to_km(bbox_lonlat, lon0, lat0):
    """Рамка (lon_min, lat_min, lon_max, lat_max) → (x0, x1, y0, y1) км, по возрастанию."""
    lo, la, ho, ha = bbox_lonlat
    x0, y0 = lonlat_to_km(lo, la, lon0, lat0)
    x1, y1 = lonlat_to_km(ho, ha, lon0, lat0)
    return (float(min(x0, x1)), float(max(x0, x1)),
            float(min(y0, y1)), float(max(y0, y1)))


def bbox_size_km(bbox_lonlat):
    """Размер рамки (ширина, высота) в км — по её собственному юго-западному углу."""
    lo, la, ho, ha = bbox_lonlat
    x0, x1, y0, y1 = bbox_lonlat_to_km(bbox_lonlat, lo, la)
    return (x1 - x0, y1 - y0)


# ----------------------------------------------------------------------
# Формат координат для показа. Три записи сразу: десятичные градусы (в них
# задают рамки участков), градусы-минуты-секунды (так подписаны бумажные карты)
# и радианы (просил заказчик).
# ----------------------------------------------------------------------
def _dms(value):
    """Градусы → (град, мин, сек) по модулю значения."""
    v = abs(float(value))
    d = int(v)
    m_full = (v - d) * 60.0
    m = int(m_full)
    s = (m_full - m) * 60.0
    if s >= 59.995:                      # округление секунд не должно давать 60.00"
        s = 0.0
        m += 1
    if m >= 60:
        m = 0
        d += 1
    return d, m, s


def format_dms(lon, lat):
    """«62°45'36.4\" N, 40°19'52.3\" E» — как подписывают бумажные карты."""
    la_d, la_m, la_s = _dms(lat)
    lo_d, lo_m, lo_s = _dms(lon)
    return ("%d°%02d'%04.1f\" %s, %d°%02d'%04.1f\" %s"
            % (la_d, la_m, la_s, "N" if lat >= 0 else "S",
               lo_d, lo_m, lo_s, "E" if lon >= 0 else "W"))


def format_deg(lon, lat):
    """«62.760100° N, 40.331200° E» — десятичные градусы, как в config.THREAT_AREAS."""
    return ("%.6f° %s, %.6f° %s"
            % (abs(lat), "N" if lat >= 0 else "S",
               abs(lon), "E" if lon >= 0 else "W"))


def format_rad(lon, lat):
    """«шир 1.095380, дол 0.703918» — радианы."""
    return "шир %.6f, дол %.6f" % (math.radians(lat), math.radians(lon))


def format_point(lon, lat, x_km=None, y_km=None):
    """Полная подпись точки для строки состояния: градусы · Г/М/С · радианы · км."""
    parts = [format_deg(lon, lat), format_dms(lon, lat), format_rad(lon, lat)]
    if x_km is not None and y_km is not None:
        parts.append("X %.2f км, Y %.2f км" % (x_km, y_km))
    return "   |   ".join(parts)
