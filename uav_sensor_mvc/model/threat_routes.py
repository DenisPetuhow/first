TURN_HARD_DEG = 45.0
# РАЗВОРОТ ЗА КОРОТКИЙ УЧАСТОК. Предела на один шаг мало: четыре шага по 45° — и аппарат
# развернулся на 180°, формально не нарушив радиуса. На карте это «пошёл вперёд, потом
# назад, потом снова вперёд» — 97 % маршрутов. Поэтому курс сравнивается ещё и с тем,
# каким он был TURN_WINDOW_KM назад: на таком отрезке нельзя отвернуть больше чем на
# TURN_WINDOW_DEG. Плавные повороты на длинной дистанции при этом разрешены.
# 0 — правило выключено.
TURN_WINDOW_KM = 3.0
TURN_WINDOW_DEG = 90.0
# ПРЯМОЙ УЧАСТОК МЕЖДУ ПОВОРОТАМИ — проверено и ВЫКЛЮЧЕНО (0). Мысль была та же:
# повороты по 45° подряд складываются в дугу радиусом 0.65 км, и если требовать между
# доворотами пройти прямо, дуга станет шире. На деле правило конфликтует с весовой картой:
# маршрут обязан следовать коридорам, а те не прямые. Замер при 2 км — доходимость
# 71 из 150 вместо 150, вес под маршрутом 16.4 -> 11.9, покрытие 25.8 -> 21.8 %; при 1 км
