# круче физики аппарата 3.5 -> 1.4 %. Покрытие области и вес под маршрутом при этом НЕ
# меняются (25.8 % и 16.3) — то есть линия стала плавной, оставшись на весовой карте.
SMOOTH_ROUNDS = 4
SMOOTH_MAX_SHIFT_KM = 0.25  # дальше этого от расчётной линии скругление не уводит
