# VIA, попавшая вплотную ЗА цель, ОТОДВИГАЕТСЯ на рубеж подхода (FINAL_APPROACH_KM), а не
# отбрасывается. На реальной сетке такая точка вставала в 2.5 км за объектом — и, будучи
# ближайшей к прямой вход→цель, выглядела для алгоритма «самой центральной»: через неё шло
# 29 % маршрутов, каждый пролетал цель насквозь и возвращался. Отодвинутая точка даёт тот
# же заход с обратной стороны, но нормальной дугой. False — прежнее поведение.
VIA_BEYOND_PUSH = True


def _spend_tau(slack_km, slack0_km, frac_done, profile):
    """«Температура» выбора соседа: чем она меньше, тем жёстче маршрут идёт к цели.

    slack_km  — СВОБОДНЫЙ ЗАПАС сейчас (км, которые ещё можно потратить на виляние);
    slack0_km — свободный запас в начале маршрута (сколько его было всего);
    frac_done — доля ВСЕГО маршрута, уже пройденная (0..1);
    profile   — из config.THREAT_SPEND_LABELS.

    Свобода вилять = (запас ещё есть) × (профиль разрешает вилять именно сейчас).
    Запас кончился — идём прямо при любом профиле (на остатке топлива не петляют).

      late  — виляет, пока запас есть (профиль не ограничивает);
      early — в начале держит курс, виляет ближе к цели (свобода растёт с frac_done);
      even  — тратит запас РАВНОМЕРНО: сверяется с «планом расхода» (к доле пути f должна
              быть истрачена доля f запаса). Идём с опережением плана — виляем свободнее;
              перерасход — выпрямляемся."""
    by_slack = min(1.0, max(0.0, slack_km) / _SLACK_FULL_KM)
    if profile == "early":              # виляем ближе к цели: в начале держим курс
        by_phase = frac_done
    elif profile == "even":             # держимся плана равномерного расхода
        spent_frac = ((slack0_km - slack_km) / slack0_km) if slack0_km > 1e-6 else 1.0
        by_phase = min(1.0, max(0.0, 0.5 + 3.0 * (frac_done - spent_frac)))
    else:                               # "late": виляем в начале, к цели выпрямляемся
        # ⚠️ ИСПРАВЛЕНО 15.09.2026 (план 11, 11.2). Было by_phase = 1: «виляет, пока запас
        # есть». Запас мерится абсолютным порогом _SLACK_FULL_KM, и при большом запасе хода
        # он не кончается никогда — маршрут вилял весь путь, как `even`. Замер при запасе
        # 129 км: извилистость первой трети 1.195, последней 1.598 (у `even` 1.200 и 1.596).
        # Теперь фаза убывает с пройденной долей — зеркально `early`.
        by_phase = 1.0 - frac_done
    return _TAU_TIGHT + (_TAU_FREE - _TAU_TIGHT) * by_slack * by_phase


_SECTOR_STENCILS = {}    # трафареты сектора: (шаг сетки, радиус, раствор) -> 8 наборов смещений


def _sector_stencils(h):
    """Смещения ячеек, попадающих в запретный сектор позади точки, — по курсу на каждого из
    8 соседей. Вход: шаг сетки, км. Отдаёт: список из 8 пар массивов (dy, dx), ячейки."""
    key = (float(h), float(BACK_SECTOR_KM), float(BACK_SECTOR_DEG))
    if key not in _SECTOR_STENCILS:                    # ещё не заготовлены
        rc = int(np.ceil(BACK_SECTOR_KM / h))          # радиус в ячейках
        dy, dx = np.mgrid[-rc:rc + 1, -rc:rc + 1]
        dist = np.hypot(dx, dy) * h                    # удаление ячейки, км
        half = np.cos(np.radians(0.5 * BACK_SECTOR_DEG))
        out = []
        for ny_, nx_, mul in _NEIGHBORS:
            ux, uy = nx_ / mul, ny_ / mul              # орт курса по x и y
            # косинус угла между «точка → ячейка» и направлением НАЗАД (−курс)
            cos_back = -(dx * ux + dy * uy) * h / np.maximum(dist, 1e-9)
            sel = (dist > 1e-9) & (dist <= BACK_SECTOR_KM) & (cos_back >= half)
            out.append((dy[sel].astype(np.int64), dx[sel].astype(np.int64)))
        _SECTOR_STENCILS[key] = out
    return _SECTOR_STENCILS[key]


def _new_trail(grid):
    """Пустая трасса маршрута для запретного сектора: маска запретных ячеек.
    Вход: сетка. Отдаёт: словарь mask (ny, nx) bool, n — сколько точек записано."""
    return dict(mask=np.zeros((grid.ny, grid.nx), bool), n=0)


def _trail_push(trail, grid, vy, vx, k):
    """Дописать точку трассы: закрасить её сектор позади в маске.
    Вход: трасса, сетка, ячейка (iy, ix), номер направления шага в `_NEIGHBORS`. Отдаёт: None."""
    sy, sx = _sector_stencils(grid.h)[k]
    yy, xx = sy + vy, sx + vx                          # ячейки сектора этой точки
    ok = (yy >= 0) & (yy < grid.ny) & (xx >= 0) & (xx < grid.nx)
    trail["mask"][yy[ok], xx[ok]] = True
    trail["n"] += 1


def _back_sector_bad(trail, grid, cy, cx):
    """Какие из 8 соседей ячейки попадают в запретный сектор позади пройденных точек.
    Вход: трасса, сетка, ячейка (iy, ix). Отдаёт: массив (8,) bool либо None (запрета нет)."""
    if trail["n"] == 0 or BACK_SECTOR_KM <= 0.0:       # трассы нет или правило выключено
        return None                                    # — запрещать нечего
    # ⚠️ МАСКА, А НЕ ПЕРЕБОР ТОЧЕК. Первая версия на каждом шаге сравнивала соседей со всеми
    # точками трассы векторно — 190 тыс. вызовов, 3.8 с на контрольный прогон (+16 %).
    # Трафарет сектора закрашивается один раз при записи точки, а проверка — чтение ячейки.
    m = trail["mask"]
    ny, nx = m.shape
    bad = np.zeros(8, bool)
    for k, (dy, dx, _mul) in enumerate(_NEIGHBORS):
        vy, vx = cy + dy, cx + dx
        if 0 <= vy < ny and 0 <= vx < nx and m[vy, vx]:   # сосед в чьём-то секторе
            bad[k] = True
    return bad


def _walk_field(ctx, dfield, start, goal, budget, turn_interval_km, rng,
                heading0=None, wmode="medium", visited=None, spend="late",
                done0_km=0.0, tail_km=0.0, dgeo=None, fscale=1.0, bypass_km=0.0,
                trail=None, reach_km=0.0):
    """Стохастический спуск по полю расстояний dfield от start к goal (надёжно приходит):
    выбор коридора — по ВЕСУ соседа (тепловая карта, приоритет по режиму wmode) и развилкам.

    ЗАПАС ХОДА расходуется осмысленно (`spend`, см. `_spend_tau`): пока свободный запас
    (остаток − кратчайший путь до цели) велик, маршрут виляет по коридорам; когда тает —
    выпрямляется и идёт к цели. Если дойти уже нельзя (остаток < кратчайшего пути) —
    обрываемся сразу, не тратя шаги. Раньше маршрут вилял «вслепую», проедал весь запас и
    отбраковывался у самой цели: на реальных данных доходило ~5 % попыток, стало ~90 %.

    ПРЯМОЛИНЕЙНОСТЬ: `turn_interval_km` — ЦЕЛЕВАЯ длина ПРЯМОГО участка: маршрут держит курс,
    пока не пролетит ~столько км, и только потом доворачивает. БЕЗ «КРУЖЕНИЯ»: посещённые
    ячейки штрафуются, «назад» по полю разрешено чуть-чуть — петли уходят.

    `visited` — общий набор пройденных ячеек (flat-индексы); для маршрута через VIA
    передаётся сквозь оба участка, чтобы они не наматывались друг на друга.

    `done0_km` / `tail_km` — участок знает своё место во ВСЁМ маршруте: сколько км уже
    пройдено ДО него и сколько минимум предстоит ПОСЛЕ (для второго участка через VIA это
    0). Без этого профиль расхода считал бы фазу пути от начала КАЖДОГО участка, и маршрут
    через VIA дважды «начинал сначала».

    Возвращает (список ячеек (y,x), длина_км, курс) или None (тупик / не хватило хода)."""
    grid = ctx["grid"]; pas = ctx["pas"]; wnorm = ctx["wnorm"]
    axis_s = ctx.get("axis_s")          # проекция ячеек на ось старт→цель (км)
    dgoal = ctx.get("dgoal")            # ПРЯМОЕ расстояние ячеек до цели (км)
    ahead = ctx.get("ahead")            # средний рельеф впереди по каждому направлению
    look_p = float(THREAT_LOOKAHEAD_POWER)   # 0 -> предвидение выключено
    ny, nx = dfield.shape
    h = grid.h
    # СПУСК идёт по `dfield` (стоимость, если она включена), а ЗАПАС ХОДА считается по
    # `dgeo` — честным километрам. Смешивать нельзя: иначе «дорогой» обход выглядел бы
    # как нехватка топлива и маршрут обрывался бы там, где физически проходит.
    if dgeo is None:
        dgeo = dfield
    d_start = dgeo[start]
    if not np.isfinite(d_start) or d_start > budget:    # цель недостижима / не хватает хода
        return None
    if not np.isfinite(dfield[start]):                  # по стоимости пути тоже нет
        return None
    # свободный запас ВСЕГО маршрута в его начале (сколько км можно потратить на виляние)
    slack0 = max(0.0, (budget + done0_km) - (d_start + tail_km + done0_km))
    # ЦЕЛЕВАЯ длина прямого участка задаётся пользователем, но в самом блуждании «держим
    # курс» лишь мягко и не дольше L_hold (жёсткая длинная прямая роняет доходимость до цели,
    # особенно на маршрутах через VIA). Итоговую ПРЯМОЛИНЕЙНОСТЬ даёт пост-обработка
    # (упрощение линии с допуском ∝ длине участка + сглаживание), см. sample_one_route.
    L_hold = min(max(1.0, float(turn_interval_km)), 6.0)
    # МАСШТАБ ПОЛЯ. `dfield` может быть стоимостным, а величины ниже заданы в КИЛОМЕТРАХ:
    # «сколько можно назад», порог «цель достигнута» и «температура» tau. Стоимостное
    # поле крупнее геометрического в среднем в `fscale` раз, и без пересчёта эти пороги
    # молча ужимались во столько же раз — стохастика падала, и вся выборка сваливалась
    # в один оптимум (см. журнал п. 154). Приводим их к единицам поля.
    fscale = max(float(fscale), 1e-6)
    back_allow = 0.8 * fscale                          # «назад» по полю (иначе тупики у стенок)
    reach_eps = h * fscale                             # порог «дошли до цели» в единицах поля
    if visited is None:
        visited = set()
    step_cap = int(6 * d_start / h + 80)
    cur = start
    visited.add(cur[0] * nx + cur[1])
    path = [cur]
    heading = heading0
    dist_since_turn = L_hold                            # на старте курс можно выбрать свободно
    route_len = 0.0
    # ИСТОРИЯ КУРСА в пределах окна разворота: пары (пройдено_км, курс). Нулевой элемент —
    # курс в начале окна, с ним и сверяется каждый кандидат (см. TURN_WINDOW_KM).
    head_hist = deque()
    if heading0 is not None:
        head_hist.append((0.0, heading0))
    # ТРАНЗИТ МИМО ЦЕЛИ: участок ведёт к VIA ЗА целью, и приближаться к объекту ближе
    # радиуса обхода ему незачем — иначе маршрут протыкает цель и возвращается. Радиус
    # задаёт вызывающий (`bypass_km`), потому что правило нужно только на таких участках;
    # поля до этих VIA считаются по той же урезанной маске (см. `pas_via`). Если участок
    # стартует внутри круга, правило не включаем — первый же шаг был бы в тупик.
    bypass = 0.0
    if (bypass_km > 0.0 and tail_km > 1e-9 and dgoal is not None
            and dgoal[start] >= bypass_km and dgoal[goal] >= bypass_km):
        bypass = float(bypass_km)
    # МЯГКОЕ ДОСТИЖЕНИЕ промежуточной точки (VIA_REACH_KM): «дошли», когда до неё по
    # коридорам осталось не больше reach_km — поворот к следующей точке начнётся дугой
    soft = float(reach_km) if (reach_km > 0.0 and tail_km > 1e-9) else 0.0   # км; у цели — строго
    for _ in range(step_cap):
        if cur == goal or dfield[cur] <= reach_eps:
            break
        if soft > 0.0 and dgeo[cur] <= soft:           # подошли к промежуточной точке
            break                                      # — участок закончен, дальше к цели
        # СВОБОДНЫЙ ЗАПАС: сколько км ещё можно потратить на виляние, оставшись в бюджете.
        # Отрицательный — дойти уже нельзя, обрываемся сразу (не жжём шаги впустую).
        # Считается по КИЛОМЕТРАМ (`dgeo`), а не по стоимости: это про топливо.
        slack = (budget - route_len) - dgeo[cur]
        if slack < 0.0:
            return None
        # доля ВСЕГО маршрута, уже пройденная (а не только текущего участка)
        done = done0_km + route_len
        remain = dgeo[cur] + tail_km
        frac_done = done / (done + remain) if (done + remain) > 1e-9 else 1.0
        # «температура» задана в км/шаг — переводим в единицы поля тем же масштабом,
        # иначе на стоимостном поле она означала бы вчетверо меньшую свободу выбора
        tau = _spend_tau(slack, slack0, frac_done, spend) * fscale
        # ФИНАЛЬНЫЙ ПОДХОД: рядом с целью запрещаем шаг ОТ неё (см. FINAL_APPROACH_KM).
        # Идти вбок и обходить по дуге по-прежнему можно — заход с другой стороны это
        # нормальный манёвр; нельзя именно «отвернуть и уйти назад» у самого объекта.
        # tail_km — остаток пути ПОСЛЕ участка: на первом участке через VIA цель ещё
        # далеко, там подход включать рано.
        in_final = (tail_km <= 1e-9 and dgoal is not None
                    and dgoal[cur] <= FINAL_APPROACH_KM)
        allow_back = 0.0 if in_final else back_allow
        cy, cx = cur
        # ДВА ПРОХОДА ПО СОСЕДЯМ. Первый — с физическим пределом поворота (TURN_MAX_DEG):
        # аппарат самолётного типа не разворачивается на месте. Если так не нашлось ни
        # одного прохода (узкий коридор, город, край области), второй проход поднимает
        # предел до аварийного — лучше некрасивый манёвр, чем оборванный маршрут и
        # потерянный кусок выборки.
        # курс в начале «окна разворота»: с ним сверяется каждый кандидат
        win_u0 = head_hist[0][1] if (head_hist and TURN_WINDOW_KM > 0.0) else None
        win_cos = float(np.cos(np.radians(TURN_WINDOW_DEG))) - 0.03
        cand, score = [], []
        # ПОРЯДОК ПОСЛАБЛЕНИЙ. Окно разворота — предпочтение, а не запрет: если с ним
        # прохода нет, оно снимается. Жёстким оно быть не может — маршрут, отвернувший
        # вбок при большом запасе хода, обязан когда-то повернуть к цели, и запрет
        # оставлял его в тупике: при L = 150 км доходило 10 маршрутов из 150.
        # держим ли сейчас прямую: доворачивать можно, только пройдя прямой участок
        hold_straight = (TURN_MIN_STRAIGHT_KM > 0.0 and heading is not None
                         and dist_since_turn < TURN_MIN_STRAIGHT_KM)
        # ЗАПРЕТНЫЙ СЕКТОР ПОЗАДИ ТРАССЫ (BACK_SECTOR_KM): считается один раз на шаг для
        # всех восьми соседей. Снимается ПОСЛЕДНИМ — после окна разворота: окно лишь
        # предпочтение, а сектор — то, ради чего возвраты и убираются.
        back_bad = _back_sector_bad(trail, grid, cy, cx) if trail is not None else None
        limits = [(TURN_MAX_DEG, True, hold_straight, True), (TURN_MAX_DEG, True, False, True),
                  (TURN_MAX_DEG, False, False, True)]
        if back_bad is not None and back_bad.any():   # сектор что-то запрещает
            limits.append((TURN_MAX_DEG, False, False, False))   # — последний шанс без него
        if TURN_HARD_DEG > TURN_MAX_DEG:
            limits.append((TURN_HARD_DEG, False, False, False))
        for turn_lim, use_win, straight, use_back in limits:
            win_u = win_u0 if use_win else None
            # ДОПУСК НА ОКРУГЛЕНИЕ: курс хранится с точностью 0.001, и у диагонали
            # скалярное произведение выходит 0.707 против точного cos 45° = 0.70711.
            # Без запаса поворот ровно на предел отсекался как «слишком крутой», и
            # оставалось единственное направление — строго прямо: из 150 маршрутов
            # строилось 7. Соседние направления сетки разнесены на 45°, так что запас
            # в 0.03 никогда не пропустит следующее (там разрыв 0.7).
            turn_cos = float(np.cos(np.radians(turn_lim))) - 0.03
            for k, (dy, dx, mul) in enumerate(_NEIGHBORS):
                vy, vx = cy + dy, cx + dx
                if vy < 0 or vy >= ny or vx < 0 or vx >= nx or not pas[vy, vx]:
                    continue
                dj = dfield[vy, vx]
                if not np.isfinite(dj) or dj > dfield[cur] + allow_back:   # к цели, почти без «назад»
                    continue
                if axis_s is not None and axis_s[vy, vx] < -START_BACK_KM:
                    continue                           # не уходить назад за точку вылета
                if in_final and dgoal[vy, vx] > dgoal[cur] + FINAL_DRIFT_KM:
                    continue                           # у цели не отворачиваем от неё
                if bypass > 0.0 and dgoal[vy, vx] < bypass:
                    continue                           # мимо цели идём в обход, а не сквозь неё
                if use_back and back_bad is not None and back_bad[k]:
                    continue                           # позади своей трассы — возврат
                uy, ux = _NB_UNIT[k]
                if heading is None:
                    hf = 1.0                           # на старте курс свободен
                else:
                    dot = uy * heading[0] + ux * heading[1]
                    if dot < turn_cos:
                        continue                       # круче, чем аппарат может развернуться
                    if straight and dot < 0.95:
                        continue                       # прямой участок ещё не выдержан
                    if win_u is not None and uy * win_u[0] + ux * win_u[1] < win_cos:
                        continue                       # разворот на коротком участке
                    if dist_since_turn < L_hold:        # держим курс (мягко — меньше зигзагов)
                        if dot > 0.9:    hf = 14.0      # прямо — сильнее всего
                        elif dot > 0.7:  hf = 2.5       # небольшой доворот — можно
                        else:            hf = 0.5       # на пределе — если нужно объехать
                    else:                               # прошли прямой участок — можно доворачивать
                        hf = 1.0 + 2.5 * max(dot, 0.0)  # но прямо всё равно охотнее
                prog = dfield[cur] - dj
                corr = _mode_corridor_pref(wnorm[vy, vx], wmode)   # приоритет по весу (режим)
                if ahead is not None and look_p > 0.0:
                    # ЧТО ЖДЁТ ДАЛЬШЕ по этому курсу: холм впереди снижает привлекательность
                    # направления заранее, за километры, а не за одну клетку до подножия
                    corr *= float(ahead[k][cy, cx]) ** look_p
                # tau мал (запас на исходе) -> exp резко выделяет соседа с макс. прогрессом
                s = float(np.exp(prog / tau)) * corr * hf
                if vy * nx + vx in visited:             # штраф за повторный заход — гасит петли,
                    s *= 0.12                           # но не запрещает (иначе тупики)
                if s <= 0.0:
                    continue
                cand.append((vy, vx, mul, (uy, ux), k)); score.append(s)
            if cand or heading is None:
                if not use_back and back_bad is not None and back_bad.any():   # прошли, сняв сектор
                    st = ctx.setdefault("_stats", {})
                    st["back_relax"] = st.get("back_relax", 0) + 1   # — счётчик для замера
                break                                   # первый проход удался — второй не нужен
        if not cand:
            return None
        # РАЗВИЛКА — «метод рулетки»: вероятность выбрать соседа ∝ его оценке score.
        # cumsum даёт нарастающие границы секторов, searchsorted находит сектор, в который
        # попала случайная точка на [0, сумма). Быстрее и без аллокаций rng.choice(p=...).
        sc = np.asarray(score, float)
        if not np.isfinite(sc).all() or sc.sum() <= 0.0:
            j = int(np.argmax(np.nan_to_num(sc, posinf=np.finfo(float).max)))   # exp переполнился
        else:                                           # при tau->0: берём лучшего соседа
            cum = np.cumsum(sc)
            j = min(int(np.searchsorted(cum, rng.random() * cum[-1])), len(cand) - 1)
        vy, vx, mul, unit, k_step = cand[j]
        step = mul * h
        route_len += step
        if route_len > budget:
            return None
        new_head = (round(unit[0], 3), round(unit[1], 3))
        dist_since_turn = (dist_since_turn + step
                           if heading is not None and new_head == heading else step)
        heading = new_head
        head_hist.append((route_len, new_head))         # окно разворота едет вместе с маршрутом
        while len(head_hist) > 1 and route_len - head_hist[0][0] > TURN_WINDOW_KM:
            head_hist.popleft()
        cur = (vy, vx)
        visited.add(vy * nx + vx)
        path.append(cur)
        if trail is not None:                           # ведём трассу для запретного сектора
            _trail_push(trail, grid, vy, vx, k_step)
    done_ok = (cur == goal or dfield[cur] <= reach_eps
               or (soft > 0.0 and dgeo[cur] <= soft))  # дошли строго или мягко
    return (path, route_len, heading) if done_ok else None


def _nearest_passable_cell(pas, grid, y_km, x_km, max_km=12.0):
    """Ближайшая проходимая ячейка к точке (км). None, если ничего в радиусе max_km."""
    iy = min(max(int(np.floor((y_km - grid.oy) / grid.h)), 0), grid.ny - 1)
    ix = min(max(int(np.floor((x_km - grid.ox) / grid.h)), 0), grid.nx - 1)
    if pas[iy, ix]:
        return (iy, ix)
    ys, xs = np.nonzero(pas)
    if len(ys) == 0:
        return None
    d2 = (ys - iy) ** 2 + (xs - ix) ** 2
    j = int(np.argmin(d2))
    r = int(round(max_km / grid.h))
    return (int(ys[j]), int(xs[j])) if d2[j] <= r * r else None


def _seg_dist_km(pt, a, b):
    """Расстояние от точки pt до ОТРЕЗКА a-b (км). Для сортировки via по «дальности обхода»."""
    p = np.asarray(pt, float); a = np.asarray(a, float); b = np.asarray(b, float)
    ab = b - a; L2 = float(ab @ ab)
    t = 0.0 if L2 < 1e-9 else float(np.clip(((p - a) @ ab) / L2, 0.0, 1.0))
    return float(np.hypot(*(p - (a + t * ab))))


def build_iter_context(grid, entry_km, target_km, max_gap_km, n_grid=(4, 5),
                       slack_km=None):
    """Подготовить (один раз, кэшируется) контекст выборки.

    `entry_km` — ОДНА точка входа (x, y) ИЛИ СПИСОК точек: при задании сектора появления
    БПЛА входов пять, и маршрут стартует из случайно выбранного. Дорогие поля (Дейкстры
    от цели и от каждой via) от входа НЕ зависят и считаются ОДИН раз на все точки —
    иначе пять входов стоили бы впятеро дороже. От входа зависит немногое, и это
    складывается в `ctx["entries"]` — по словарю на точку:
      * `start`      — ячейка входа;
      * `axis_s`     — проекция ячеек на ось вход→цель (правило «не уходить за старт»);
      * `via_minlen` — минимальная длина пути вход→via→цель ИМЕННО ИЗ ЭТОГО входа;
      * `gt_start`, `reachable` — расстояние до цели и достижима ли она.
    Поля первой точки продублированы на верхнем уровне — ради кода, который знает про
    один вход (`ctx["start"]`, показатели интерфейса).

    VIA-точки — СЕТКА по всей
    проходимой области (все стороны, включая юг/восток и «за целью» — заход в Б с ЛЮБОГО
    направления, если хватает хода), с предвычисленными полями расстояний. Каждой via
    сопоставлены:
      * `via_segd`  — «дальность обхода» (расстояние до отрезка вход→цель), для разброса;
      * `via_minlen` — МИНИМАЛЬНАЯ длина пути вход→via→цель. Маршрут через via физически
        возможен, только если via_minlen ≤ запаса хода. Раньше это не проверялось, и
        половина via была заведомо недостижима — каждая попытка через них гарантированно
        проваливалась (см. `_pick_via`);
      * `via_togoal` — кратчайший путь via→цель: столько хода надо ОСТАВИТЬ на второй участок.

    Порог мостика через провал = `max_gap_km` (разрыв между весовыми секторами, из
    интерфейса). Контекст зависит от разрыва и от цели, но НЕ от запаса хода L_max —
    поэтому кэшируется и переиспользуется при смене L_max."""
    entries_km = _as_entry_list(entry_km)
    starts = [_cell_of(grid, e) for e in entries_km]
    start = starts[0]                      # «представитель» для общих полей и совместимости
    goal = _cell_of(grid, target_km)
    # концы открываем у ВСЕХ входов: непроходимая ячейка входа отрезала бы свою точку
    pas = _open_endpoints(passable_mask(grid, max_gap_km, slack_km),
                          tuple(starts) + (goal,), grid)
    ahead = _lookahead_fields(grid, THREAT_LOOKAHEAD_KM)   # что ждёт впереди по курсу
    w = np.clip(grid.weight, 0.0, None)                 # нормировка веса по p90 (как в стоимости)
    pos = w[w > 0]
    ref = float(np.percentile(pos, 90)) if pos.size else 1.0
    wnorm = np.clip(w / max(ref, 1e-6), 0.0, 1.0)
    # ДВА ПОЛЯ РАССТОЯНИЙ ДО ЦЕЛИ, потому что вопросов два:
    #   gt_geo — честные километры: «хватит ли запаса хода» (физику подменять нельзя);
    #   gt     — стоимость в км-эквивалентах: «куда выгоднее идти» (по ней идёт спуск).
    # При THREAT_COST_POWER = 0 второе совпадает с первым — прежнее поведение.
    mul = _cost_mul(grid, wnorm, THREAT_COST_POWER, THREAT_COST_RELIEF)
    gt_geo = _dijkstra_dist(pas, goal, grid.h)
    gt = gt_geo if mul is None else _dijkstra_cost(pas, goal, grid.h, mul)
    # ВО СКОЛЬКО РАЗ стоимостное поле крупнее геометрического. По нему приводятся к
    # единицам поля пороги, заданные в километрах («температура» tau, допуск «назад»,
    # порог «дошли»). Считаем по ПРОХОДИМЫМ ячейкам — остальные к делу не относятся.
    if mul is None:
        cost_scale = 1.0
    else:
        m_ok = np.asarray(mul, float)[pas]
        cost_scale = float(m_ok.mean()) if m_ok.size else 1.0
    # НАБОР ПОЛЕЙ «жадности»: от чистой геометрии до полной стоимости. Каждое считается
    # СВОЕЙ Дейкстрой по множителю `1 + a·(mul − 1)`, поэтому остаётся корректным полем
    # расстояний — в отличие от линейной смеси готовых полей, где появляются локальные
    # минимумы-ловушки и маршрут не доходит.
    gt_mix = []
    if mul is not None and THREAT_COST_MIX_BIAS > 0.0:
        m = np.asarray(mul, float)
        for a in THREAT_COST_MIX_STEPS:
            if a <= 0.0:
                fld, sc = gt_geo, 1.0
            elif a >= 1.0:
                fld, sc = gt, cost_scale
            else:
                ma = 1.0 + a * (m - 1.0)
                fld = _dijkstra_cost(pas, goal, grid.h, ma)
                sc = float(ma[pas].mean()) if pas.any() else 1.0
            gt_mix.append(dict(a=float(a), gt=fld, scale=sc, via=[]))
    # ОСЬ «вход→цель» и «дальность обхода» считаются от ЦЕНТРА входов: при нескольких
    # точках общая ось одна, а разброс даёт сама стартовая ячейка. Иначе пришлось бы
    # дублировать via-поля на каждый вход — впятеро дороже при том же результате.
    A = np.asarray(entries_km, float).mean(axis=0)
    B = np.asarray(target_km, float)
    ab = float(np.hypot(*(B - A))) or 1.0
    # Проекция каждой ячейки на ось старт→цель (км): 0 у старта, ab у цели, отрицательная —
    # ПОЗАДИ старта; и ПРЯМОЕ расстояние ячейки до цели. Именно последнее видно на карте:
    # расстояние по коридорам (`gt`) может быть вдвое больше, и по нему зона подхода
    # срабатывала не там, где кажется глазу.
    gxc, gyc = grid.cell_centers_km()
    axis_s = ((gxc - A[0]) * (B[0] - A[0]) + (gyc - A[1]) * (B[1] - A[1])) / ab
    dgoal = np.hypot(gxc - B[0], gyc - B[1])
    # МАСКА ТРАНЗИТА — только для VIA ЗА ЦЕЛЬЮ. По ней считаются поля до таких точек: путь
    # к ним ведёт мимо объекта, и приближаться к нему вплотную незачем (то же правило, что
    # в `_walk_field`). Считать по ней поля ДО ВСЕХ VIA нельзя: обычным маршрутам она
    # закрывает коридоры у самой цели, и вес под выборкой падает на 12 %.
    pas_via = pas
    push_km = FINAL_APPROACH_KM if VIA_BEYOND_PUSH else 0.0   # 0 — не отодвигать (как было)
    if FINAL_BYPASS_KM > 0.0 and float(dgoal[start]) >= FINAL_BYPASS_KM:
        pas_via = pas & (dgoal >= FINAL_BYPASS_KM)
        # VIA за целью ставится ВНЕ круга обхода, с зазором на дискретизацию сетки: точка
        # ровно на границе попадала бы в ячейку, куда шаг уже запрещён.
        if VIA_BEYOND_PUSH:
            push_km = FINAL_BYPASS_KM + 2.0 * grid.h
    via_cell, via_gv, via_gv_geo = [], [], []
    via_segd, via_togoal, via_back = [], [], []
    if np.isfinite(gt[start]):
        ys, xs = np.nonzero(pas & np.isfinite(gt))     # достижимые проходимые ячейки
        if len(ys):
            gy = np.linspace(ys.min(), ys.max(), n_grid[0])
            gx = np.linspace(xs.min(), xs.max(), n_grid[1])
            for cy in gy:
                for cx in gx:
                    vc = _nearest_passable_cell(pas, grid,
                                                grid.oy + (cy + 0.5) * grid.h,
                                                grid.ox + (cx + 0.5) * grid.h, max_km=18.0)
                    if vc is None or vc in via_cell or vc == goal or vc == start:
                        continue
                    vxk = grid.ox + (vc[1] + 0.5) * grid.h
                    vyk = grid.oy + (vc[0] + 0.5) * grid.h
                    # VIA не должна лежать ПОЗАДИ старта или ЗА целью: маршрут через
                    # такую точку сперва уходит в сторону, обратную цели, либо пролетает
                    # мимо цели и возвращается — на карте это выглядит как «полетел не
                    # туда». Небольшой заступ допустим (обход препятствия у самой точки).
                    s_axis = float((np.array([vxk, vyk]) - A) @ (B - A)) / ab
                    if s_axis < -VIA_BEHIND_KM or s_axis > ab + VIA_BEYOND_KM:
                        continue
                    # VIA рядом с целью, но НЕ за ней, заставляет маршрут отвернуть у
                    # самого объекта и вернуться — на карте это «дёрнулся в сторону в
                    # пяти километрах от цели». Заход ЗА цель — штатный манёвр, но и он
                    # должен быть ОБХОДОМ: точка вплотную за объектом (на реальной сетке
                    # 2.5 км) заставляет маршрут пролететь цель насквозь и вернуться.
                    # Такую VIA отодвигаем по лучу от цели на рубеж подхода — заход
                    # остаётся, «клевок» пропадает (см. VIA_BEYOND_PUSH).
                    d_via_goal = float(np.hypot(vxk - B[0], vyk - B[1]))
                    if d_via_goal < FINAL_APPROACH_KM and s_axis <= ab:
                        continue
                    if d_via_goal < push_km and s_axis > ab:
                        # Точка ЗА целью, но вплотную к ней: отодвигаем по лучу от цели за
                        # круг обхода (с зазором на дискретизацию сетки), чтобы маршрут
                        # огибал объект, а не протыкал его.
                        d = np.array([vxk - B[0], vyk - B[1]], float)
                        n = float(np.hypot(*d))
                        d = d / n if n > 1e-6 else (B - A) / ab   # точно на оси — вдоль неё
                        out = B + d * push_km
                        vc2 = _nearest_passable_cell(pas_via, grid, out[1], out[0], max_km=12.0)
                        if vc2 is None or vc2 in via_cell or vc2 == goal or vc2 == start:
                            continue
                        vc = vc2
                        vxk = grid.ox + (vc[1] + 0.5) * grid.h
                        vyk = grid.oy + (vc[0] + 0.5) * grid.h
                        s_axis = float((np.array([vxk, vyk]) - A) @ (B - A)) / ab
                    # два поля ОТ этой via: геометрия — для бюджета, стоимость — для спуска.
                    # Для точки ЗА ЦЕЛЬЮ — по маске транзита (обход объекта), для остальных
                    # по обычной: им закрывать коридоры у цели незачем.
                    back = bool(s_axis > ab and pas_via is not pas)
                    pmask = pas_via if back else pas
                    if not pmask[vc]:
                        continue                       # сама точка внутри круга обхода
                    gv_geo = _dijkstra_dist(pmask, vc, grid.h)
                    gv = gv_geo if mul is None else _dijkstra_cost(pmask, vc, grid.h, mul)
                    if not any(np.isfinite(gv_geo[s]) for s in starts):
                        continue     # в обход цели до неё не добраться НИ ИЗ ОДНОГО входа
                    via_cell.append(vc)
                    via_back.append(back)
                    via_gv.append(gv)
                    via_gv_geo.append(gv_geo)
                    # то же для каждой «жадности» — иначе первый участок через via шёл бы
                    # по другой логике, чем второй, и повадка маршрута ломалась посередине
                    for f in gt_mix:
                        if f["a"] <= 0.0:
                            f["via"].append(gv_geo)
                        elif f["a"] >= 1.0:
                            f["via"].append(gv)
                        else:
                            f["via"].append(_dijkstra_cost(
                                pmask, vc, grid.h,
                                1.0 + f["a"] * (np.asarray(mul, float) - 1.0)))
                    via_segd.append(_seg_dist_km((vxk, vyk), A, B))
                    # «сколько хода оставить на второй участок» и «уложимся ли вообще» —
                    # это КИЛОМЕТРЫ. Путь via→цель берём из поля ОТ ЦЕЛИ (`gt_geo`): оно
                    # считано по полной маске, а поле от via — по маске транзита, где сама
                    # цель вырезана кругом обхода и расстояние до неё было бы бесконечным.
                    via_togoal.append(float(gt_geo[vc]))
                    # `via_minlen` здесь НЕ считается: длина вход→via→цель своя у каждой
                    # точки входа и собирается ниже, в надстройках по входам
    # СРЕДНЕЕ расстояние от точек входа до цели — от него считаются пояса облёта
    D_mean = float(np.mean([np.hypot(ex - B[0], ey - B[1]) for ex, ey in entries_km]))
    orbit = _orbit_pool(grid, pas_via, gt_geo, mul, B, D_mean)   # маска с кругом обхода цели
    # НАДСТРОЙКИ ПО ВХОДАМ: всё, что зависит от точки старта. Поля выше общие.
    togoal_arr = np.asarray(via_togoal, float)
    entries = []
    for (ex, ey), sc in zip(entries_km, starts):
        d = B - np.array([ex, ey], float)
        abe = float(np.hypot(*d)) or 1.0
        entries.append(dict(
            start=sc, entry_km=(float(ex), float(ey)), ab=abe,
            # своя ось «этот вход → цель»: по ней работает запрет ухода назад за старт
            axis_s=((gxc - ex) * d[0] + (gyc - ey) * d[1]) / abe,
            # «уложится ли маршрут через via» — тоже своё: из разных входов путь разный
            via_minlen=(np.asarray([float(g[sc]) for g in via_gv_geo]) + togoal_arr
                        if via_gv_geo else np.zeros(0)),
            gt_start=float(gt_geo[sc]),
            # азимут «цель → вход», градусы (0 — север, по часовой): для паузы повтора по углу
            az=float(np.degrees(np.arctan2(ex - B[0], ey - B[1])) % 360.0),
            reachable=bool(np.isfinite(gt_geo[sc]))))
    live = [e for e in entries if e["reachable"]]
    ctx = dict(grid=grid, pas=pas, gt=gt, gt_geo=gt_geo, wnorm=wnorm,
               cost_scale=cost_scale, gt_mix=gt_mix, goal=goal,
               dgoal=dgoal, ahead=ahead,
               via_cell=via_cell, via_gv=via_gv, via_gv_geo=via_gv_geo,
               via_back=np.asarray(via_back, bool), via_segd=np.asarray(via_segd),
               via_togoal=togoal_arr, entries=entries, orbit=orbit,
               # ⚠️ СЧЁТЧИК ЖИВЁТ В САМОМ КОНТЕКСТЕ массивом: маршрут работает с копией
               # `{**ctx, **вход}`, и прибавка на месте видна всем следующим маршрутам
               _orbit_done=(np.zeros(len(orbit["sectors"])) if orbit else None),   # дошедших облётов по поясам, шт.
               _appr_done=({k: np.zeros(3) for k in ("min", "medium", "max")}
                           if orbit else None),        # дошедших по повадкам на уровень, шт.
               target_km=(float(B[0]), float(B[1])),
               entry_span_deg=_azimuth_span([e["az"] for e in entries]),   # разнос входов, градусы
               # ОСЬ ОТ ЦЕНТРА входов — по ней считались via_segd и «via за целью»
               axis_center=axis_s, ab_center=ab)
    # для кода, знающего про один вход (`ctx["start"]`, показатели, `_pick_via`):
    # представитель — первый ДОСТИЖИМЫЙ вход, иначе просто первый
    ctx.update(live[0] if live else entries[0])
    return ctx


def _orbit_pool(grid, pmask, gt_geo, mul, B, D):
    """Точки облёта по ПОЯСАМ вокруг цели, границы — доли среднего расстояния вход→цель.
    Вход: сетка, маска (с кругом обхода цели), поле км до цели, множитель цены, цель B км,
    D — среднее расстояние от входов до цели, км. Отдаёт: словарь sectors, bounds (км), D."""
    import config as _cfg                              # читаем при вызове: опыты подменяют
    frac = tuple(float(f) for f in getattr(_cfg, "THREAT_ORBIT_RADII_FRAC", ()))
    ndir = int(getattr(_cfg, "THREAT_ORBIT_DIRS", 12))
    mix = getattr(_cfg, "THREAT_APPROACH_MIX", {})
    if (len(frac) < 2 or ndir < 4 or D <= 0.0
            or not any(p[1] + p[2] > 0 for p in mix.values())):   # облёт выключен
        return {}                                      # — поясов не строим
    # ⚠️ ПОЯСА В ДОЛЯХ, А НЕ В КМ (заказчик 16.09.2026): кольца 10/18/28 км в районе 200 км
    # жались бы к цели. Граница пояса = доля × D; ближний пояс не заходит в круг обхода цели —
    # туда шаг и так запрещён, точка там была бы недостижима.
    bounds = [f * D for f in frac]                     # границы поясов, км
    r_min = FINAL_BYPASS_KM + 2.0 * grid.h             # ближе к цели точку не ставим, км
    x0, y0 = grid.ox, grid.oy
    x1, y1 = grid.ox + grid.nx * grid.h, grid.oy + grid.ny * grid.h   # рамка сетки, км
    step = 2.0 * np.pi / ndir                          # шаг азимута, радианы
    sectors = []
    rows = 2                                           # рядов в поясе: 0 — ближний, 1 — дальний
    for s in range(len(bounds) - 1):
        r_in, r_out = max(bounds[s], r_min), bounds[s + 1]
        slots = []
        if r_out <= r_in:                              # пояс целиком внутри круга обхода
            sectors.append(slots)                      # — точек нет
            continue
        # ⚠️ ДВА РЯДА СО СДВИГОМ в КАЖДОМ поясе (11.5): точка берётся по случайному углу, и чем
        # гуще пул, тем разнообразнее облёт; а разброс выбирает ряд — «прямая» ближний, «края»
        # дальний, — не меняя доли самого пояса. У рамки района второй ряд часто остаётся один.
        for row in range(rows):
            r = r_in + (r_out - r_in) * (row + 0.5) / rows     # радиус ряда, км
            for k in range(ndir):
                a = step * (k + 0.5 * row)             # азимут точки, радианы (от оси x)
                px, py = B[0] + r * np.cos(a), B[1] + r * np.sin(a)
                if not (x0 <= px < x1 and y0 <= py < y1):   # точка за рамкой района
                    continue                           # — с этой стороны пояса нет
                vc = _nearest_passable_cell(pmask, grid, py, px,
                                            max_km=0.5 * (r_out - r_in) / rows + grid.h)
                if vc is None or not np.isfinite(gt_geo[vc]):   # проходимого рядом нет
                    continue
                vx_k = grid.ox + (vc[1] + 0.5) * grid.h
                vy_k = grid.oy + (vc[0] + 0.5) * grid.h
                rr = float(np.hypot(vx_k - B[0], vy_k - B[1]))
                if not (r_in - grid.h <= rr <= r_out + grid.h):   # примагнитилась мимо пояса
                    continue
                # ⚠️ ПОЛЯ ЛЕНИВО (`_ring_fields`): точек около сотни, а нужны единицы.
                slots.append(dict(sector=s, row=row, a=float(np.arctan2(vy_k - B[1], vx_k - B[0])),
                                  r=rr, cell=vc, xy=(vx_k, vy_k), togoal=float(gt_geo[vc]),
                                  pmask=pmask, mul=mul, gv_geo=None, gv=None))
        sectors.append(slots)
    return dict(sectors=sectors, bounds=bounds, D=float(D))


def _ring_fields(grid, slot):
    """Посчитать поля расстояний к точке облёта, если ещё не считались (кэш в самой точке).
    Вход: сетка, точка (словарь). Отдаёт: None; заполняет gv_geo (км) и gv (стоимость)."""
    if slot["gv_geo"] is not None:                     # уже посчитано
        return
    slot["gv_geo"] = _dijkstra_dist(slot["pmask"], slot["cell"], grid.h)
    slot["gv"] = (slot["gv_geo"] if slot["mul"] is None
                  else _dijkstra_cost(slot["pmask"], slot["cell"], grid.h, slot["mul"]))


def _deg_diff(a, b):
    """Разность азимутов, приведённая в [0, 180]. Вход: градусы. Отдаёт: градусы."""
    return abs((float(a) - float(b) + 180.0) % 360.0 - 180.0)


def _azimuth_span(azs):
    """Разнос азимутов по кругу: 360° минус наибольший промежуток между соседними.
    Вход: азимуты, градусы. Отдаёт: градусы (0 — точка одна)."""
    a = np.sort(np.asarray(azs, float) % 360.0)
    if len(a) < 2:                                     # точка одна или ни одной
        return 0.0
    gaps = np.diff(np.concatenate([a, [a[0] + 360.0]]))   # промежутки по кругу, градусы
    return float(360.0 - gaps.max())


def _angle_diff(a, b):
    """Разность углов, приведённая в [0, π]. Вход: радианы. Отдаёт: радианы."""
    return abs((a - b + np.pi) % (2.0 * np.pi) - np.pi)


def _quota_order(share, done, rng):
    """Порядок, в котором пробовать варианты (пояса облёта, повадки): первым — разыгранный с
    учётом недобора. Вход: доли вариантов (сумма 1), дошедших маршрутов по вариантам (шт.),
    генератор. Отдаёт: список номеров вариантов (все, без повторов)."""
    # ⚠️ ДОЛЯ ДЕРЖИТСЯ СРЕДИ ДОШЕДШИХ (заказчик 16.09.2026: «чтобы всегда процент такой был»).
    # Простой розыгрыш по долям её не держит: дальний облёт чаще не укладывается в запас или
    # упирается в рамку. В 11.4 «края» заказывали дальнему поясу 15 %, а получали 5 %; уровень
    # «максимальный» заказывал облёту 35 %, а в выборку попадало 25 %. Поэтому вес варианта = его
    # доля плюс недобор в маршрутах; перевес ограничен ORBIT_QUOTA_CAP, чтобы вариант, который не
    # даётся вовсе, не забирал себе все попытки.
    N = float(done.sum())                              # дошедших маршрутов всего, шт.
    w = np.clip(share * (N + 1.0) - done, 0.0, ORBIT_QUOTA_CAP)   # вес варианта, маршрутов
    left = list(range(len(share)))
    order = []
    while left:
        ww = np.asarray([w[s] for s in left], float)
        if ww.sum() <= 0.0:                            # у оставшихся недобора нет
            ww = np.asarray([share[s] for s in left], float) + 1e-9   # — просто по долям
        k = int(np.searchsorted(np.cumsum(ww), rng.random() * ww.sum()))
        order.append(left.pop(min(k, len(left) - 1)))
    return order


def _orbit_chain(ctx, behav, spread, rng, L_max):
    """Цепочка точек облёта для flank/rear: пояс по долям с учётом недобора, углы — случайно.
    Вход: контекст (со своим входом), повадка, режим разброса (без mix), генератор, запас км.
    Отдаёт: (список точек, номер пояса) либо (None, None) — облёт не по силам ни в каком поясе."""
    orb = ctx.get("orbit") or {}
    if not orb:                                        # поясов нет
        return None, None
    import config as _cfg
    sectors = orb["sectors"]
    share = np.asarray(tuple(_cfg.THREAT_ORBIT_SECTOR_SHARE)[:len(sectors)], float)
    share = share / max(float(share.sum()), 1e-9)      # доли поясов, сумма 1
    done = ctx.get("_orbit_done")                      # дошедших облётов по поясам, шт.
    if done is None or len(done) != len(sectors):      # контекст собран без счётчика
        done = np.zeros(len(sectors))                  # — считаем, что недобора нет
    B = np.asarray(ctx["target_km"], float)
    ex, ey = ctx["entry_km"]
    ae = float(np.arctan2(ey - B[1], ex - B[0]))       # азимут стороны входа, радианы
    side = 1.0 if rng.random() < 0.5 else -1.0         # обход по или против часовой
    # УГЛЫ СЛУЧАЙНО В ПРЕДЕЛАХ ПОВАДКИ — маршруты облёта не должны быть одним и тем же путём
    offs = [np.radians(60.0 + 60.0 * rng.random())]    # сбоку: 60–120° от стороны входа
    if behav == "rear":                                # облёт: ещё 135–180°
        offs.append(np.radians(135.0 + 45.0 * rng.random()))
    row = {"center": 0, "edge": 1}.get(spread)         # ряд пояса по разбросу; None — любой
    for s in _quota_order(share, done, rng):
        chain = _chain_in_belt(ctx, sectors, s, ae, side, offs, row, L_max)
        if chain is not None:                          # в этом поясе облёт по силам
            st = ctx.setdefault("_stats", {})
            st["orbit_sector_%d" % s] = st.get("orbit_sector_%d" % s, 0) + 1   # для замера
            return chain, s
    return None, None                                  # облёт не по силам ни в каком поясе


def _chain_in_belt(ctx, sectors, s, ae, side, offs, row, L_max):
    """Цепочка облёта с точкой отхода в поясе s. Вход: контекст, пул поясов, номер пояса,
    азимут входа (радианы), сторона ±1, углы от стороны входа (радианы), ряд или None, запас км.
    Отдаёт: список точек либо None — в этом поясе облёт не по силам."""
    tol = np.radians(35.0)                             # точка не дальше 35° от нужного угла
    grid = ctx["grid"]
    ex, ey = ctx["entry_km"]
    s_cell = ctx["start"]

    def nearest(pool, want):
        """Ближайшая по углу точка пула в допуске, с рядом разброса, если он есть; иначе None."""
        cand = [c for c in pool if _angle_diff(c["a"], want) <= tol]
        pref = [c for c in cand if c["row"] == row] if row is not None else cand
        cand = pref or cand                            # нужного ряда нет — любой ряд пояса
        return min(cand, key=lambda c: _angle_diff(c["a"], want)) if cand else None

    for sd in (side, -side):
        first = nearest(sectors[s], ae + sd * offs[0])   # точка ОТХОДА — строго в поясе s
        if first is None:                              # в поясе с этой стороны дыра
            continue
        # ЗАХОД С ОБРАТНОЙ СТОРОНЫ — в том же поясе или ближе к цели: за целью рамка района часто
        # ближе, чем сбоку (в эталоне 36.5 км против 60), и дальний пояс там пуст. Пояс маршрута
        # всё равно задаёт точка отхода — именно она уводит маршрут в сторону.
        seconds = [None]
        if len(offs) > 1:                              # облёт: нужна вторая точка
            seconds = [nearest(sectors[sb], ae + sd * offs[1]) for sb in range(s, -1, -1)]
            seconds = [c for c in seconds if c is not None and c is not first]
        for second in seconds:
            chain = [first] if second is None else [first, second]
            pts = [(ex, ey)] + [c["xy"] for c in chain]
            lb = sum(float(np.hypot(b[0] - a[0], b[1] - a[1])) for a, b in zip(pts, pts[1:]))
            if lb + chain[-1]["togoal"] > L_max:       # даже по прямым не укладывается
                continue                               # — пробуем заход ближе к цели
            for c in chain:
                _ring_fields(grid, c)                  # поля — по первому спросу
            minlen = chain[0]["gv_geo"][s_cell]        # вход → первая точка, км
            for a, b in zip(chain, chain[1:]):
                minlen += a["gv_geo"][b["cell"]]       # от точки к точке, км
            minlen += chain[-1]["togoal"]              # последняя точка → цель, км
            if np.isfinite(minlen) and minlen <= L_max:   # по коридорам тоже укладывается
                return chain
    return None                                        # в поясе s облёт не по силам


def _pick_via(ctx, spread, rng, L_max):
    """Выбрать индекс VIA по режиму РАЗБРОСА (по дальности обхода segd): center — близкие к
    прямой, edge — дальние (юг/восток/за целью), middle — средние, mix — любая. None = прямо.

    Сначала отбрасываем VIA, ЧЕРЕЗ КОТОРЫЕ НЕ ХВАТИТ ХОДА: путь вход→via→цель не короче
    `via_minlen`, и если это больше L_max — маршрут через неё невозможен, сколько ни
    пробуй. Раньше такие via разыгрывались наравне с остальными (на реальных данных —
    половина всех точек), и каждая попытка через них была гарантированным отказом."""
    segd = ctx["via_segd"]
    if len(segd) == 0:
        return None
    minlen = ctx["via_minlen"]
    ok = np.nonzero(np.isfinite(minlen) & (minlen <= L_max))[0]   # достижимые при этом ходе
    if len(ok) == 0:
        return None                                    # ни одна via не по силам — только прямой
    sp = ("center", "middle", "edge")[rng.integers(3)] if spread == "mix" else spread
    order = ok[np.argsort(segd[ok])]                   # от близких к прямой к дальним
    n = len(order)
    if sp == "center":
        pool = order[:max(1, n // 3)]
    elif sp == "edge":
        pool = order[-max(1, n // 2):]                 # дальние (включая юг/восток/за B)
    else:                                              # middle
        lo, hi = n // 4, max(n // 4 + 1, 3 * n // 4)
        pool = order[lo:hi]
        if len(pool) == 0:                             # мало via — берём что есть
            pool = order
    return int(pool[rng.integers(len(pool))])


def _off_corridor(poly, grid, pas):
    """Сколько точек линии вышло за ПРОХОДИМУЮ зону (город / провал шире разрыва)."""
    ix = np.clip(((poly[:, 0] - grid.ox) / grid.h).astype(np.int64), 0, grid.nx - 1)
    iy = np.clip(((poly[:, 1] - grid.oy) / grid.h).astype(np.int64), 0, grid.ny - 1)
    return int((~pas[iy, ix]).sum())


def _mean_weight(poly, grid):
    """Средний вес карты под линией — по ячейкам, через которые она проходит."""
    w = grid.weight
    ix = np.clip(((poly[:, 0] - grid.ox) / grid.h).astype(np.int64), 0, grid.nx - 1)
    iy = np.clip(((poly[:, 1] - grid.oy) / grid.h).astype(np.int64), 0, grid.ny - 1)
    return float(np.clip(w[iy, ix], 0.0, None).mean())


def _round_corners(poly, raw, rounds, max_shift):
    """Скруглить остаточную угловатость линии, не уводя её от расчётного пути.

    Каждый проход подтягивает точку к середине соседей: p -> (p_пред + 2p + p_след)/4.
    Концы (вход и цель) не двигаются. После каждого прохода точка, отошедшая от расчётной
    ломаной дальше `max_shift`, возвращается — иначе на длинных дугах сглаживание
    «спрямляло» бы линию и уводило с коридора."""
    if rounds <= 0 or len(poly) < 5:
        return poly
    P = np.array(poly, float)
    R = np.asarray(raw, float)
    for _ in range(int(rounds)):
        Q = P.copy()
        Q[1:-1] = 0.25 * P[:-2] + 0.5 * P[1:-1] + 0.25 * P[2:]
        if max_shift > 0.0:
            # расстояние каждой новой точки до расчётной ломаной (по её вершинам)
            d = np.hypot(Q[:, 0][:, None] - R[None, :, 0],
                         Q[:, 1][:, None] - R[None, :, 1]).min(axis=1)
            far = d > max_shift
            if far.any():
                Q[far] = P[far]
        P = Q
    return P


def _smooth_safe(raw, grid, pas, eps0):
    """Сгладить ломаную, НЕ ВЫВОДЯ её из коридора и НЕ УВОДЯ с весовой карты.

    Упрощение (RDP) с большим допуском спрямляет маршрут, но срезает углы — и линия
    может уйти туда, куда БПЛА не летит (плотная застройка, провал шире разрыва).
    Раньше так и было: сама ломаная по ячейкам всегда лежала в коридоре, а СГЛАЖЕННАЯ
    кривая — та, что рисуется и по которой считаются датчики, — срезала углы через город.

    ВТОРОЕ ТРЕБОВАНИЕ, не менее важное: срезая угол, кривая уходит с тяжёлого коридора —
    реки или дороги, ради которых маршрут и прокладывался. Формально она остаётся
    проходимой (пустошь не запрещена), но смысл теряется: показываем не тот путь, который
    посчитали. Поэтому сглаженная линия обязана сохранить вес расчётной ломаной с точностью
    до SMOOTH_WEIGHT_KEEP.

    Допуск подбирается: пробуем заданный, и пока кривая режет запретное или теряет вес —
    уменьшаем вдвое (углы срезаются меньше, линия жмётся к расчётной). В пределе
    возвращаем сглаживание по опорным точкам сетки — оно из коридора не выходит.

    Порядок проверок выбран из соображений скорости: упрощение (RDP) дёшево, сплайн —
    дорого, поэтому сначала отбраковываем по упрощённой ломаной и только уцелевшую
    доводим сплайном."""
    w_raw = _mean_weight(raw, grid) if SMOOTH_WEIGHT_KEEP > 0.0 else 0.0
    need = SMOOTH_WEIGHT_KEEP * w_raw
    eps = float(eps0)
    best = None
    for _ in range(5):
        simp = _rdp(raw, eps=eps)
        if _off_corridor(simp, grid, pas) == 0:    # дёшево: ломаная уже режет запретное?
            poly = _catmull_rom(simp)
            if _off_corridor(poly, grid, pas) == 0:
                # скругление применяем ТОЛЬКО если оно само не портит линию: и коридор,
                # и вес проверяются заново — иначе берём кривую без него
                soft = _round_corners(poly, raw, SMOOTH_ROUNDS, SMOOTH_MAX_SHIFT_KM)
                if (soft is not poly and _off_corridor(soft, grid, pas) == 0
                        and (need <= 0.0 or _mean_weight(soft, grid) >= need)):
                    return soft
                if need <= 0.0 or _mean_weight(poly, grid) >= need:
                    return poly
                if best is None:                   # запасной вариант: коридор цел, вес просел
                    best = poly
        eps *= 0.5
    poly = _catmull_rom(raw)                       # без упрощения: кривая идёт по ячейкам
    if _off_corridor(poly, grid, pas) == 0:
        return poly
    return best if best is not None else raw


def sample_one_route(ctx, mode, L_max, turn_interval_km, rng, spread="mix", spend="late",
                     approach="mix"):
    """ОДИН стохастический маршрут вход→цель. mode = приоритет клетки по ВЕСУ
    (max/medium/min/mix). spread = РАЗБРОС по карте (center/middle/edge/mix) — через какую
    VIA-точку строить (center — вдоль прямой, edge — дальний обход/заход с любой стороны).
    spend = профиль РАСХОДА ЗАПАСА ХОДА (late/early/even, см. `_spend_tau`).
    approach = уровень ОБЛЁТА ЦЕЛИ (min/medium/max/mix, см. `_pick_approach`).
    None, если не уложились в запас хода.

    ТОЧКА ВХОДА разыгрывается здесь: если задан сектор появления, их пять, и каждая
    имеет РАВНЫЕ шансы (решение заказчика: вес местности участвует при ОТБОРЕ самих
    пяти точек, а не при выборе старта). Недостижимые точки в розыгрыш не идут — иначе
    треть попыток тратилась бы впустую.

    ПАУЗА ПОВТОРА (`THREAT_SECTOR_ENTRY_COOLDOWN` = 2): точка, из которой только что
    стартовали, не берётся следующие два раза. Равномерный розыгрыш сам по себе даёт
    серии («выпало трижды подряд»), и на коротких прогонах часть точек не отрабатывала
    вовсе. История последних выборов лежит в самом контексте, поэтому правило работает
    и в `plan_routes`, и в итерациях — они делят один контекст. Если доступных точек
    не осталось (недостижимые), пауза снимается: маршрут важнее ровности чередования."""
    ents = ctx.get("entries")
    picked = None                           # номер разыгранной точки входа; None — вход один
    if ents and len(ents) > 1:
        live = [i for i, e in enumerate(ents) if e["reachable"]]
        if not live:
            return None
        recent = ctx.setdefault("_recent_entries", [])
        cool = max(0, int(THREAT_SECTOR_ENTRY_COOLDOWN))
        avail = [i for i in live if i not in recent[-cool:]] if cool else live
        if not avail:                       # точек меньше, чем длина паузы
            avail = live
        # ПАУЗА ПО УГЛУ (план 11, 11.6, заказчик 16.09.2026): старт не берётся в зоне шириной
        # THREAT_ENTRY_COOLDOWN_DEG вокруг стартов последних THREAT_ENTRY_COOLDOWN_ROUTES маршрутов.
        # ⚠️ Только при разносе точек шире (маршрутов + 1) × зона: в секторе 60° правило запретило
        # бы всё — там остаётся пауза по номеру, и случайность тратится ровно как раньше.
        n_ang = max(0, int(THREAT_ENTRY_COOLDOWN_ROUTES))       # сколько стартов помнить
        zone = float(THREAT_ENTRY_COOLDOWN_DEG)                  # ширина зоны, градусы
        # ⚠️ ПОМНИМ СТАРТЫ ДОШЕДШИХ МАРШРУТОВ, а не попыток: заказчик говорил о «следующих
        # маршрутах». По попыткам (как пауза по номеру) замер дал 28 нарушений зоны на 150
        # принятых маршрутов — не дошедшая попытка занимала место в истории.
        recent_ok = ctx.setdefault("_recent_ok_entries", [])      # старты дошедших, номера точек
        if n_ang and recent_ok and ctx.get("entry_span_deg", 0.0) > (n_ang + 1) * zone:   # точки разнесены
            last = [ents[j]["az"] for j in recent_ok[-n_ang:]]   # азимуты недавних стартов
            far = [i for i in live
                   if all(_deg_diff(ents[i]["az"], a) >= 0.5 * zone for a in last)]
            if far:                         # есть точки вне всех зон
                avail = far                 # — берём из них; нет — остаётся пауза по номеру
        # РАВНОМЕРНО: при неизвестном нарушителе это честнее, чем взвешивать по весу
        pick = avail[int(rng.integers(len(avail)))]
        recent.append(pick)
        del recent[:-8]                     # история нужна короткая, не растим список
        ctx = {**ctx, **ents[pick]}
        picked = pick
    if not ctx["reachable"]:
        return None
    wmode = ("max", "medium", "min")[rng.integers(3)] if mode == "mix" else mode
    if spend == "mix":                                  # веер всех повадок (для «возможных путей»)
        spend = ("late", "early", "even")[rng.integers(3)]
    # «ЖАДНОСТЬ» ЭТОГО маршрута: какое из предрассчитанных полей взять — от чисто
    # геометрического (летит напрямик) до полностью стоимостного (жмётся к коридорам и
    # низинам). Одного поля мало: если путь A дешевле B на десятки единиц, локальная
    # стохастика туда не уведёт, и вся выборка сваливается в один оптимум.
    fields = ctx.get("gt_mix")
    if fields:
        u = float(rng.random()) ** float(THREAT_COST_MIX_BIAS)
        fi = min(int(u * len(fields)), len(fields) - 1)
        fmix, gt_use = fields[fi]["scale"], fields[fi]["gt"]
        via_use = fields[fi]["via"]
    else:
        fmix, gt_use, via_use = ctx.get("cost_scale", 1.0), ctx["gt"], ctx["via_gv"]
    grid = ctx["grid"]
    # ТРАССА ДЛЯ ЗАПРЕТНОГО СЕКТОРА — одна на весь маршрут: второй участок через VIA обязан
    # видеть трассу первого, иначе возврат «дошёл до VIA и пошёл обратно» остался бы
    trail = _new_trail(grid) if BACK_SECTOR_KM > 0.0 else None
    # ПОВАДКА ЗАХОДА (план 11, 11.3–11.4): обычный заход, сбоку или облёт — отдельным
    # критерием; разброс решает, в каком поясе облёт. Поясов нет — случайность не
    # тратится, и выборка прежняя до бита.
    behav, spread, lvl = _pick_approach(ctx, approach, spread, rng)
    chain, belt = (_orbit_chain(ctx, behav, spread, rng, L_max) if behav != "direct"
                   else (None, None))                   # цепочка облёта и её пояс
    st = ctx.setdefault("_stats", {})
    if behav != "direct":                               # разыграли облёт
        key = ("appr_try_" if chain is not None else "appr_nohop_") + behav
        st[key] = st.get(key, 0) + 1                    # — счётчик для замера
    if chain is not None:                               # облёт по цепочке точек кольца
        a_fld = fields[fi]["a"] if fields else 1.0      # «жадность»: 0 — геометрия
        cells = _walk_chain(ctx, chain, gt_use, fmix, a_fld, L_max, turn_interval_km,
                            rng, wmode, spend, trail)
        j = -1                                          # метка: путь уже построен
    else:
        behav = "direct"
        j = (None if (spread == "center" and rng.random() < 0.5)
             else _pick_via(ctx, spread, rng, L_max))
    if j == -1:                                         # облёт построен выше
        pass
    elif j is None:                                     # прямой маршрут (через центр)
        r = _walk_field(ctx, gt_use, ctx["start"], ctx["goal"], L_max,
                        turn_interval_km, rng, wmode=wmode, spend=spend,
                        dgeo=ctx.get("gt_geo"), fscale=fmix, trail=trail)
        cells = r[0] if r else None
    else:                                               # через VIA (обход/заход со стороны)
        via = ctx["via_cell"][j]
        togoal = float(ctx["via_togoal"][j])
        # На участок via→цель надо ОСТАВИТЬ хода не меньше кратчайшего пути оттуда, иначе
        # первый участок проест весь запас и второй гарантированно не дойдёт.
        budget1 = L_max - togoal
        if budget1 <= 0.0:
            return None
        # tail_km/done0_km: участки знают своё место во всём маршруте — иначе профиль
        # расхода отсчитывал бы фазу пути заново от каждого из них.
        gv_geo = ctx.get("via_gv_geo")
        g1 = gv_geo[j] if gv_geo else None
        f1 = via_use[j] if (via_use and j < len(via_use)) else ctx["via_gv"][j]
        # VIA ЗА ЦЕЛЬЮ: участок к ней обходит объект по дуге (тот же радиус, по которому
        # считалось поле), а не протыкает его насквозь. Для остальных точек правило не
        # нужно — им у цели делать нечего и без запрета.
        vb = ctx.get("via_back")
        back = bool(vb is not None and len(vb) > j and vb[j])
        r1 = _walk_field(ctx, f1, ctx["start"], via, budget1,
                         turn_interval_km, rng, wmode=wmode, spend=spend,
                         done0_km=0.0, tail_km=togoal, dgeo=g1, fscale=fmix,
                         bypass_km=(FINAL_BYPASS_KM if back else 0.0), trail=trail,
                         reach_km=VIA_REACH_KM)
        if r1 is None:                                  # каждый участок — свой набор visited
            return None
        if VIA_REACH_KM > 0.0:                          # мягкая VIA
            via = r1[0][-1]                             # — второй участок оттуда, куда пришли
        r2 = _walk_field(ctx, gt_use, via, ctx["goal"], L_max - r1[1],
                         turn_interval_km, rng, heading0=r1[2], wmode=wmode, spend=spend,
                         done0_km=r1[1], tail_km=0.0, dgeo=ctx.get("gt_geo"), fscale=fmix,
                         trail=trail)
        if r2 is None:
            return None
        cells = r1[0] + r2[0][1:]                        # склейка без дубля via
    if cells is None or len(cells) < 2:
        return None
    # ПРЯМОЛИНЕЙНОСТЬ ∝ «длине прямого участка»: чем она больше, тем крупнее допуск упрощения
    # (RDP) -> тем длиннее прямые звенья и тем прямее маршрут. Затем интерполяция Катмулла–Рома
    # делает повороты плавными ДУГАМИ, а прямые оставляет прямыми (плавно «дугами и прямыми»).
    # Допуск подбирается так, чтобы сглаженная кривая НЕ вышла из коридора (см. _smooth_safe).
    eps = float(np.clip(turn_interval_km * SMOOTH_EPS_FRAC, grid.h * 1.2, 8.0))
    poly = _smooth_safe(_cells_yx_to_km(grid, cells), grid, ctx["pas"], eps)
    # Запас хода — строго: длина маршрута не может его превышать (сглаживание маршрут
    # только СПРЯМЛЯЕТ, т.е. укорачивает, поэтому прежний допуск ×1.15 был лишним).
    if _poly_len_km(poly) > L_max:                      # не уложился в запас
        return None
    st["last_belt"] = -1 if behav == "direct" else belt  # пояс этого маршрута — для замера
    st["last_behav"] = behav                            # повадка этого маршрута — для замера
    appr = (ctx.get("_appr_done") or {}).get(lvl)       # счётчик повадок уровня
    if appr is not None:                                # облёт включён
        appr[BEHAVS.index(behav)] += 1                  # — повадка получила своё
    if behav != "direct":                               # облёт дошёл — счётчики
        st["appr_ok_" + behav] = st.get("appr_ok_" + behav, 0) + 1
        done = ctx.get("_orbit_done")
        if done is not None and 0 <= belt < len(done):  # счётчик поясов есть
            done[belt] += 1                             # — пояс получил своё, недобор меньше
        D = ctx["orbit"]["D"]
        st.setdefault("orbit_rD", []).append(          # радиус облёта этого маршрута / D
            float(np.mean([c["r"] for c in chain])) / D if D > 0 else float("nan"))
    if picked is not None:                              # старт разыгран из нескольких точек
        ok_hist = ctx["_recent_ok_entries"]             # тот же список, что в общем контексте
        ok_hist.append(picked)                          # — маршрут дошёл: старт в историю паузы по углу
        del ok_hist[:-8]                                # история нужна короткая
    return poly


BEHAVS = ("direct", "flank", "rear")                    # повадки захода в порядке долей config


def _pick_approach(ctx, approach, spread, rng):
    """Разыграть повадку захода по долям уровня облёта (config.THREAT_APPROACH_MIX) с учётом
    недобора (`_quota_order`). Вход: контекст, уровень облёта (min/medium/max/mix), режим
    разброса, генератор. Отдаёт: (повадка, режим разброса — для облёта без mix, уровень или None)."""
    if not ctx.get("orbit"):                            # поясов облёта нет
        return "direct", spread, None                   # — случайность не тратим
    import config as _cfg                               # читаем при вызове: опыты подменяют
    lvl = ("min", "medium", "max")[rng.integers(3)] if approach == "mix" else approach
    p = np.asarray(_cfg.THREAT_APPROACH_MIX.get(lvl, (1.0, 0.0, 0.0)), float)
    p = p / max(float(p.sum()), 1e-9)                   # доли повадок уровня, сумма 1
    done = (ctx.get("_appr_done") or {}).get(lvl)       # дошедших по повадкам этого уровня, шт.
    if done is None:                                    # контекст без счётчика
        done = np.zeros(len(BEHAVS))                    # — недобора нет
    behav = BEHAVS[_quota_order(p, done, rng)[0]]
    if behav == "direct":                               # обычный заход
        return behav, spread, lvl                       # разброс разыграет `_pick_via`
    sp = ("center", "middle", "edge")[rng.integers(3)] if spread == "mix" else spread
    return behav, sp, lvl


def _walk_chain(ctx, chain, gt_use, fmix, a_fld, L_max, turn_interval_km, rng,
                wmode, spend, trail):
    """Облёт: вход → точки кольца по порядку → цель, участок за участком.
    Вход: контекст, цепочка точек кольца, поле к цели, масштаб поля, «жадность» (0 — геометрия),
    запас км, длина прямого км, генератор, режимы, трасса. Отдаёт: ячейки пути или None."""
    # сколько хода минимум понадобится ПОСЛЕ каждого участка: до следующих точек и цели, км
    tails = []
    for i in range(len(chain)):
        t = chain[-1]["togoal"]
        for a, b in zip(chain[i:], chain[i + 1:]):
            t += a["gv_geo"][b["cell"]]
        tails.append(float(t))
    cur, done, heading = ctx["start"], 0.0, None
    cells = [cur]
    for wp, tail in zip(chain, tails):
        fld = wp["gv_geo"] if a_fld <= 0.0 else wp["gv"]   # геометрия или стоимость, как у маршрута
        r = _walk_field(ctx, fld, cur, wp["cell"], L_max - done - tail, turn_interval_km, rng,
                        heading0=heading, wmode=wmode, spend=spend, done0_km=done,
                        tail_km=tail, dgeo=wp["gv_geo"], fscale=fmix,
                        bypass_km=FINAL_BYPASS_KM, trail=trail, reach_km=VIA_REACH_KM)
        if r is None:                                   # участок не дошёл
            return None
        cells += r[0][1:]
        done += r[1]
        heading = r[2]
        cur = r[0][-1]
    r = _walk_field(ctx, gt_use, cur, ctx["goal"], L_max - done, turn_interval_km, rng,
                    heading0=heading, wmode=wmode, spend=spend, done0_km=done, tail_km=0.0,
                    dgeo=ctx.get("gt_geo"), fscale=fmix, trail=trail)
    if r is None:                                       # последний участок к цели не дошёл
        return None
    return cells + r[0][1:]
