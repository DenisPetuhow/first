# -*- coding: utf-8 -*-
"""
ТИПЫ ДАТЧИКОВ И ДАТЧИКИ, ЗАДАННЫЕ ЧЕЛОВЕКОМ (задача 8.7).

Здесь живут две вещи, которых раньше в модели не было:

* **четыре типа датчиков** вместо двух. Типы 1–3 — малые (сеть по маршрутам), тип 4 —
  большие (круговой щит у цели). У каждого своё число, свой радиус и своя кратность;
* **датчик, поставленный человеком** — с типом и режимом (динамический / статический).

⚠️ ПОЧЕМУ ЗДЕСЬ НЕТ СВОИХ ЧИСЕЛ. Значения параметров — только в `config.Params`, это
правило проекта. Модуль ничего не хранит: он лишь СОБИРАЕТ разрозненные поля `Params`
(`threat_N`, `threat_R2`, …) в удобный список `SensorSpec` и разбирает их обратно.
Единственный источник истины — по-прежнему `Params`.

⚠️ ПОЧЕМУ СТАРЫЕ ИМЕНА ОСТАЛИСЬ. `threat_N`, `threat_R`, `threat_k`, `threat_N_big`,
`threat_R_big` читаются в десятке мест (расстановка, показатели, автошаг сетки, эталон,
окна интерфейса) — переименование расползлось бы по всему проекту ради косметики.
Поэтому тип 1 и тип 4 — это ровно они, а новыми полями заведены только типы 2 и 3.
Соответствие: тип 1 ← `threat_N`/`threat_R`, тип 2 ← `threat_N2`/`threat_R2`,
тип 3 ← `threat_N3`/`threat_R3`, тип 4 ← `threat_N_big`/`threat_R_big`.

СПРАВОЧНИК ТИПОВ (план 13, задача 13.1, 23.09.2026). Названия, палитра, правило места и
режим типа — паспорт из `src/model/placement/sensor_types.py`; он приходит в `SensorSpec.passport`.
Числа номеров 1–4 по-прежнему из полей выше (переходный мост до 13.3 и 13.10); малые типы
справочника с номером ≥ 5 берут R и k из паспорта, N — из `threat_N_types`.
"""
from dataclasses import dataclass

SMALL_TYPES = (1, 2, 3)        # малые: сеть по маршрутам, общий CoverageCache
BIG_TYPE = 4                   # большие: круговой щит у цели, своё правило (кольцо)
TYPE_IDS = SMALL_TYPES + (BIG_TYPE,)

# Поля Params, отвечающие за каждый тип: (число, радиус, кратность).
# Кратность типа 4 отдельным полем НЕ заведена: большие ставятся кольцом по УГЛУ, и
# кратность в их расстановке не участвует — параметр, который никто не читает, только
# сбивал бы с толку (его же поймал бы check_dead_code.py). В окне поле у типа 4
# показывается общим, из threat_k.
_FIELDS = {
    1: ("threat_N",     "threat_R",     "threat_k"),
    2: ("threat_N2",    "threat_R2",    "threat_k2"),
    3: ("threat_N3",    "threat_R3",    "threat_k3"),
    4: ("threat_N_big", "threat_R_big", "threat_k"),
}

KIND_LABEL = {"small": "малый", "big": "большой"}


@dataclass
class SensorSpec:
    """Параметры ОДНОГО типа датчиков: сколько, какого радиуса, с какой кратностью."""
    type_id: int
    n: int
    r_km: float
    k: int
    kind: str                  # "small" (типы 1–3) | "big" (тип 4)
    passport: object = None    # паспорт `sensor_types.SensorType`; None — номера нет в справочнике

    @property
    def active(self):
        """Тип участвует в расстановке. Пустой тип (N = 0) — не ошибка, а «не нужен»:
        так заказчик выключает лишние типы, не удаляя их настройки."""
        return int(self.n) > 0 and float(self.r_km) > 0.0

    @property
    def name(self):
        """Название типа: из паспорта; номера нет в справочнике — «Тип N». Отдаёт: строку."""
        return self.passport.name if self.passport is not None else "Тип %d" % self.type_id


@dataclass
class ManualSensor:
    """Датчик, ЗАДАННЫЙ ЧЕЛОВЕКОМ: мышью по карте, строкой в таблице или из файла.

    ⚠️ Координаты — в КИЛОМЕТРАХ рабочего фрейма, как и всё остальное в модели. В файл
    они пишутся в градусах (формат 8.7.7): градусы самодостаточны и переносятся между
    участками, а километры зависят от якоря области.

    `static=True` — позиция не меняется НИ ПРИ КАКИХ УСЛОВИЯХ: алгоритм принимает её как
    данность и достраивает остальные датчики вокруг. `static=False` — датчик обычный,
    его позицию выбирает жадный алгоритм (запись в таблице тогда лишь задаёт тип).

    `placed` — СЛУЖЕБНОЕ, только для показа: учтён ли датчик последней расстановкой.
    ⚠️ Нужно из-за динамических. Пока расстановки не было, поставленный мышью датчик
    рисуется прямо в точке клика — иначе непонятно, попал ли клик куда целились. После
    расстановки динамический уезжает туда, где его поставил алгоритм, и точку клика
    показывать НЕЛЬЗЯ: на карте оставался значок, и выглядело это так, будто режимы не
    различаются и датчик «не двигается» (замечание заказчика 05.09.2026)."""
    type_id: int
    static: bool
    x_km: float
    y_km: float
    placed: bool = False


def _num(p, name, default=0):
    """Прочитать поле Params, пережив его отсутствие (старые сохранённые настройки)."""
    return getattr(p, name, default)


def sensor_types(p, catalog=None):
    """Типы задания по возрастанию номера. Вход: Params, справочник (None — файл участка).
    Отдаёт: [SensorSpec] — номера 1–4 всегда (числа из полей Params), малые ≥ 5 — из справочника."""
    from model.placement import sensor_types as catalog_mod
    types = catalog_mod.load() if catalog is None else catalog   # паспорта типов
    passport = {t.type_id: t for t in types}                     # номер -> паспорт
    # ⚠️ Кратность — по галке `threat_k_same`: «одна на всех» — общая `threat_k` у каждого
    # типа, иначе своя. Дублируется ЗДЕСЬ, а не при расчёте: в окне видно то число, с которым считают.
    same = bool(_num(p, "threat_k_same", True))
    k_all = int(_num(p, "threat_k", 3) or 1)
    out = []
    for tid in TYPE_IDS:
        f_n, f_r, f_k = _FIELDS[tid]
        k = k_all if same else int(_num(p, f_k, k_all) or 1)
        out.append(SensorSpec(
            type_id=tid,
            n=int(_num(p, f_n, 0) or 0),
            r_km=float(_num(p, f_r, 0.0) or 0.0),
            k=max(1, k),
            kind="big" if tid == BIG_TYPE else "small",
            passport=passport.get(tid)))
    n_more = _n_types(p)                                         # задание новых типов: номер -> N
    for t in sorted(types, key=lambda t: t.type_id):              # типы справочника по номеру
        if t.type_id in TYPE_IDS:                                # номер моста — уже собран выше
            continue
        if t.SPEC_KIND != "small":                               # большой с номером ≥ 5
            continue                                             # — кольцо умеет только номер 4 (13.9)
        out.append(SensorSpec(
            type_id=t.type_id, n=n_more.get(t.type_id, 0), r_km=float(t.r_km),
            k=max(1, k_all if same else int(t.k)), kind="small", passport=t))
    return out


def _n_types(p):
    """Число датчиков у типов с номером ≥ 5. Вход: Params. Отдаёт: {номер: N}.
    Ключ приводится к int: из сохранённых настроек он приходит строкой."""
    out = {}
    for key, n in dict(_num(p, "threat_N_types", {}) or {}).items():   # номер типа → сколько ставить
        try:
            out[int(key)] = max(0, int(n))
        except (TypeError, ValueError):                          # битая запись задания
            continue                                             # — тип просто не ставится
    return out


def type_ids(p):
    """Номера всех типов задания — то, что вправе стоять в `ManualSensor.type_id`.
    Вход: Params. Отдаёт: кортеж номеров по возрастанию."""
    return tuple(s.type_id for s in sensor_types(p))


def active_small(p):
    """Малые типы, которые реально нужно ставить (N > 0)."""
    return [s for s in sensor_types(p) if s.kind == "small" and s.active]


def min_small_radius(p):
    """Наименьший радиус работающих малых типов «везде» — по нему шаг общей сетки кандидатов.
    Вход: Params. Отдаёт: км; типов «везде» нет — радиус типа 1 (общей сеткой никто не ставится)."""
    act = active_small(p)                            # работающие малые типы
    # ⚠️ ТИП С ПРАВИЛОМ МЕСТА ОБЩИЙ ШАГ НЕ ДРОБИТ (план 13, 13.5): у него своя сетка шагом R/2 внутри
    # карты, и ПВН (0.5 км) иначе мельчил бы сетку МОГ по всему району
    free = [s for s in act if s.passport is None or s.passport.zone == "везде"]   # типы «везде»
    # ⚠️ одни ограниченные — общей сеткой не пользуется никто, шаг как без малых: иначе ПВН 0.5 км мельчил её
    # вчетверо, когда МОГ стал «дорогой» (план 13.3)
    if free:                                         # есть типы «везде» — шаг по самому мелкому
        # ⚠️ по минимальному, а не по первому: шаг крупнее обзора оставляет между кандидатами дыру. Замер (R 2 км,
        # 5 датчиков, 150 маршрутов): шаг 0.5 км — засечка 96.7 %, 3 км — 82.7 %, 6 км — 17.3 %
        return min(float(s.r_km) for s in free)
    return float(_num(p, "threat_R", 2.0) or 2.0)    # общей сеткой не ставится никто


def format_types_header(p):
    """Шапка файла датчиков — таблица типов (формат 8.7.7). Возвращает список строк
    БЕЗ знака `#`: его добавляет тот, кто пишет файл."""
    rows = ["типы датчиков:",
            "  тип  класс    N   R, км   кратность k"]
    for s in sensor_types(p):
        rows.append("  %3d  %-7s %3d  %6.1f  %6d"
                    % (s.type_id, KIND_LABEL.get(s.kind, s.kind), s.n, s.r_km, s.k))
    return rows
