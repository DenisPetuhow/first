    para("СГЛАЖИВАНИЕ (сплайн Катмулла–Рома) — наоборот добавляет точки:", bold=True)
    bullet("по четырём соседним точкам строит гладкую кривую между двумя средними;")
    bullet("проходит РОВНО через исходные точки, а не рядом с ними — маршрут не уезжает "
           "с расчётного;")
    bullet("на прямых совпадает с прямой, изгиб появляется только у поворотов.")
    warn("Нужны оба: без упрощения сплайн сглаживал бы каждую мелкую дрожь по ячейкам и "
         "линия виляла бы; без сплайна остались бы резкие углы, а аппарат так не летает.")
