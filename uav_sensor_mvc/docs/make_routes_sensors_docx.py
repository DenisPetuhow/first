# -*- coding: utf-8 -*-
"""
Генератор Word-документа «Маршруты и датчики: теория и код».

Запуск:  python docs/make_routes_sensors_docx.py
Результат: docs/Маршруты_и_датчики.docx

Что внутри: как СЕЙЧАС построена модель движения и расстановка — теория, формулы,
числа замеров и короткие фрагменты настоящего кода. Документ пересобирается скриптом;
руками его не правят (правка уйдёт при следующей сборке).

Требуется python-docx (pip install python-docx).
"""
import os

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Inches, Pt, RGBColor

_HERE = os.path.dirname(os.path.abspath(__file__))   # папка docs/
PIC_DIR = os.path.join(_HERE, "картинки")   # рисунки к документу, их строит make_pictures.py

ACCENT = RGBColor(0x1F, 0x4E, 0x79)      # синий заголовков
MUTED = RGBColor(0x55, 0x55, 0x55)       # серый пояснений
WARN = RGBColor(0xA6, 0x1B, 0x1B)        # красный предупреждений
CODE_BG = RGBColor(0x1F, 0x3A, 0x55)     # тёмно-синий кода


def build():
    # Собрать документ целиком. Вход: ничего. Отдаёт: объект Document.
    doc = Document()
    base = doc.styles["Normal"]
    base.font.name = "Calibri"
    base.font.size = Pt(11)

    def h(text, level=1):
        p = doc.add_heading(text, level=level)
        for r in p.runs:
            r.font.color.rgb = ACCENT
        return p

    def para(text="", bold=False, italic=False, size=None, color=None, align=None):
        p = doc.add_paragraph()
        r = p.add_run(text)
        r.bold = bold
        r.italic = italic
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = color
        if align:
            p.alignment = align
        return p

    def warn(text):
        # Предупреждение — красным: места, где легко ошибиться.
        return para("⚠ " + text, color=WARN)

    def formula(text):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Pt(24)
        r = p.add_run(text)
        r.italic = True
        r.font.name = "Consolas"
        r.font.size = Pt(11)
        return p

    def code(lines, caption=None):
        # Фрагмент кода: моноширинный, с отступом и подписью откуда он.
        if caption:
            para(caption, italic=True, size=9, color=MUTED)
        for line in lines:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Pt(18)
            p.paragraph_format.space_after = Pt(0)
            r = p.add_run(line if line else " ")
            r.font.name = "Consolas"
            r.font.size = Pt(9.5)
            r.font.color.rgb = CODE_BG
        doc.add_paragraph()

    def pic(name, caption, width_in=6.3):
        """Картинка из `docs/картинки/` с подписью. Вход: имя файла без .png, подпись,
        ширина в дюймах. Отдаёт: None. ⚠️ Нет файла — вместо картинки пишем, чем её собрать:
        документ должен собираться и на машине, где картинки ещё не строили."""
        path = os.path.join(PIC_DIR, name + ".png")
        if not os.path.exists(path):
            warn("картинка «%s» не собрана — запустите: python docs/make_pictures.py" % name)
            return
        doc.add_picture(path, width=Inches(width_in))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        para(caption, italic=True, size=9, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)

    def bullet(text, head=None):
        p = doc.add_paragraph(style="List Bullet")
        if head:
            p.add_run(head + " ").bold = True
        p.add_run(text)
        return p

    def table(head, rows):
        # Таблица с шапкой. Вход: список заголовков, список строк. Отдаёт: таблицу.
        t = doc.add_table(rows=1, cols=len(head))
        t.style = "Light Grid Accent 1"
        for i, name in enumerate(head):
            cell = t.rows[0].cells[i]
            cell.text = ""
            r = cell.paragraphs[0].add_run(name)
            r.bold = True
            r.font.size = Pt(10)
        for row in rows:
            cells = t.add_row().cells
            for i, val in enumerate(row):
                cells[i].text = ""
                r = cells[i].paragraphs[0].add_run(str(val))
                r.font.size = Pt(10)
        doc.add_paragraph()
        return t

    # ==================================================================
    # ТИТУЛ
    # ==================================================================
    t = doc.add_heading("Маршруты и датчики: как это работает сейчас", level=0)
    for r in t.runs:
        r.font.color.rgb = ACCENT
    para("Теория, формулы и фрагменты кода — состояние на 23.09.2026; "
         "разделы 17а–17г (хранение маршрутов, таблица «маршрут × место», оптимизация) — 26.09.2026",
         italic=True, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)
    para("Документ описывает ДЕЙСТВУЮЩУЮ механику: как рождается один маршрут, "
         "как из множества маршрутов получаются позиции датчиков, какие критерии "
         "максимизируются и какими числами это подтверждено.",
         color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)
    para("Все числа — из замеров на участке «arh», район из файла области "
         "(120.5 × 73.0 км), если не сказано иное.",
         italic=True, size=9, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)

    # ==================================================================
    h("Часть I. МАРШРУТЫ", 1)
    # ==================================================================
    h("1. Что именно строится", 2)
    para("Строится не один маршрут, а ВЫБОРКА правдоподобных путей. Причина простая: "
         "всего возможных маршрутов в районе — 7.24 · 10¹⁶² (величина считается точно, "
         "динамическим программированием от цели наружу). Их нельзя ни перечислить, ни "
         "нарисовать, а показать «типичный» — значит дать неверный ответ.")
    para("Полная картина «где БПЛА может оказаться» — это ЗАКРАШЕННАЯ ОБЛАСТЬ (область "
         "залёта): множество точек, куда он способен долететь по пути вход → точка → цель "
         "в пределах запаса хода. Она точна. Линии же показывают, КАК это выглядит.")
    formula("область залёта = { P : путь(вход→P) + путь(P→цель) ≤ L_max }")

    h("2. Точки входа: откуда появляется БПЛА", 2)
    para("Маршрут начинается не в одной точке. Если задан сектор появления, программа "
         "отбирает на краю района ПЯТЬ точек входа, и каждый маршрут стартует из одной "
         "из них.")
    para("Отбор идёт не по весу самой приграничной ячейки, а по ПЕРСПЕКТИВЕ ДВИЖЕНИЯ — "
         "среднему весу прямоугольника, вытянутого от точки в сторону цели (5 × 3 ячейки, "
         "то есть 2.5 × 1.5 км):")
    bullet("кандидаты берутся из полосы вдоль края шириной 1 км;")
    bullet("точка обязана стоять на весовой ячейке — иначе это чистое поле без ориентиров;")
    bullet("точка обязана быть достижимой: из неё должен существовать путь до цели;")
    bullet("точки разводятся и по расстоянию — не ближе 3 % от (ширина + высота) района, у "
           "района 120 × 73 км это 5.8 км, — и по углу (0.3 идеального шага). Не набралось "
           "точек — пороги спускаются ступенями ×0.6 (5.8 → 3.5 → 2.1 км …), а не сразу в ноль.")
    warn("Вес приграничной ячейки отражает лишь то, попал ли край карты на дорогу: у "
         "половины кандидатов он ровно 0. Замер: лучшая по ячейке точка оказалась по "
         "перспективе только 13-й, а перспективность отобранной пятёрки выросла "
         "21.9 → 28.1 (+28 %).")
    para("СТАРТ разыгрывается между пятью точками РАВНОМЕРНО. Вес местности участвует, "
         "когда эти пять отбираются, а не когда выбирается старт: нарушитель неизвестен, "
         "и взвешивать его появление нечем.")
    para("Чтобы равномерность не вырождалась в серии («выпало трижды подряд»), работают "
         "две паузы повтора:")
    table(["Пауза", "Величина", "Что делает"],
          [["по номеру", "2 розыгрыша",
            "точка, только что давшая старт, не берётся следующие два раза"],
           ["по углу", "45° вокруг стартов 3 последних ДОШЕДШИХ маршрутов",
            "включается, когда точки разнесены шире 180°"]])
    warn("Пауза по углу считает ДОШЕДШИЕ маршруты, а не попытки: по попыткам замер дал "
         "28 нарушений зоны на 150 маршрутов, по дошедшим — 0.")

    h("3. Четыре случайные оси одного маршрута", 2)
    para("Каждому маршруту разыгрываются четыре независимых свойства — они и делают "
         "выборку разнообразной:")
    table(["Ось", "Значения", "Что задаёт"],
          [["вес", "макс. / средний / мин. / смесь",
            "тянуться к тяжёлым коридорам (реки, дороги) или прятаться в пустошах"],
           ["разброс", "центр / середина / края / смесь",
            "через какую промежуточную точку (VIA) идти"],
           ["расход хода", "виляет-потом-прямо / прямо-потом-виляет / равномерно",
            "когда тратить свободный запас на манёвры"],
           ["облёт цели", "85/10/5 · 60/25/15 · 30/35/35 · смесь",
            "как часто заходить сбоку и с обратной стороны"]])
    para("Плюс пятая, скрытая ось — «жадность»: какое из заранее посчитанных полей "
         "стоимости взять, от чисто геометрического (летит напрямик) до полностью "
         "стоимостного (жмётся к коридорам и низинам).")
    warn("Без этой оси вся выборка сваливалась в один оптимум: если путь A дешевле B на "
         "десятки единиц, локальная случайность туда не уведёт.")

    h("4. Шаг движения: три множителя и рулетка", 2)
    para("Маршрут идёт по ячейкам весовой сетки 500 × 500 м. На каждом шаге оцениваются "
         "все восемь соседей, и следующий выбирается «рулеткой» — вероятность "
         "пропорциональна оценке:")
    formula("s = exp(prog / tau) · corr · hf")
    table(["Множитель", "Что выражает", "Что будет без него"],
          [["exp(prog / tau)", "стремление к цели (prog — насколько сосед ближе)",
            "маршрут бродит и не долетает"],
           ["corr", "привлекательность местности по режиму веса",
            "летит напрямик, коридоры ни при чём"],
           ["hf", "удержание курса (14.0 прямо, 0.5 на пределе поворота)",
            "зигзаг: физика аппарата нарушена"]])
    code(["prog = dfield[cur] - dj                      # насколько сосед БЛИЖЕ к цели",
          "corr = _mode_corridor_pref(wnorm[vy, vx], wmode)   # вес по режиму панели",
          "s = float(np.exp(prog / tau)) * corr * hf   # оценка соседа",
          "if vy * nx + vx in visited:",
          "    s *= 0.12                               # был здесь — гасим петли, не запрещаем",
          "",
          "sc = np.asarray(score, float)               # РУЛЕТКА: вероятность ∝ оценке",
          "j = int(np.searchsorted(np.cumsum(sc), rng.random() * sc.sum()))"],
         "model/threat_routes.py :: _walk_field")
    para("Величина tau — «температура» — считается из свободного запаса хода: "
         "slack = остаток хода − кратчайший путь до цели. Запас тает, tau падает, "
         "экспонента резко выделяет лучшего соседа — и маршрут перестаёт петлять сам, "
         "без отдельного правила.")
    warn("Повторный заход в ячейку штрафуется (×0.12), но НЕ запрещается: запрет загонял "
         "бы маршрут в тупики, где единственный выход — вернуться на шаг назад.")

    para("Соседи проверяются ДВУМЯ проходами. Первый — с физическим пределом поворота: "
         "аппарат самолётного типа не разворачивается на месте, и курс сверяется с тем, "
         "что был в начале окна разворота. Если так не прошёл ни один сосед (узкий коридор, "
         "город, край области), второй проход поднимает предел до аварийного.")
    warn("Заказчик 20.09.2026: правильнее не дотягивать маршрут нефизичным разворотом, а "
         "браковать его и разыгрывать заново. Это записано задачей; цена известна — сейчас "
         "51 % попыток и так уходит впустую, отказов станет больше.")
    para("Рядом с целью действует ФИНАЛЬНЫЙ ПОДХОД: ближе рубежа 10 км шаг «от цели» "
         "запрещён вовсе. Идти вбок и обходить по дуге можно — это штатный манёвр; нельзя "
         "именно отвернуть и уйти назад у самого объекта.")

    h("5. Почему не ищем кратчайший путь", 2)
    para("Алгоритмы вроде Дейкстры или A* (на них построены автомобильные навигаторы) "
         "дают ОДИН самый дешёвый путь. Здесь это неверный ответ: вопрос не «куда "
         "полетит идеальный аппарат», а «где он может оказаться». Единственная линия "
         "не отвечает на него даже приближённо.")
    para("Задача коммивояжёра тоже не подходит: она про обход набора точек по "
         "кратчайшему кругу, а у нас маршрут идёт из одной точки в другую.")
    para("Из приёмов маршрутизации в программе применяются ровно два, и оба — на этапе "
         "оформления линии: упрощение Дугласа–Пекера (RDP) и сглаживание сплайном "
         "Катмулла–Рома.")

    h("6. Точки обхода (VIA)", 2)
    para("VIA — промежуточная точка, через которую маршрут обязан пройти. Она и делает "
         "выборку широкой: без неё все линии шли бы по самому дешёвому коридору.")
    para("Набор считается ОДИН РАЗ на выборку, потому что на каждую точку нужны свои поля "
         "расстояний (Дейкстра по всей сетке). Порядок такой:")
    bullet("прямоугольник достижимых ячеек делится сеткой 4 × 5 = 20 узлов;")
    bullet("узел притягивается к ближайшей проходимой ячейке (поиск до 18 км);")
    bullet("отсев: позади старта дальше 1 км · за целью дальше 10 км · ближе 10 км к цели, "
           "не будучи за ней;")
    bullet("точка вплотную ЗА целью не выбрасывается, а отодвигается по лучу за круг "
           "обхода — заход сзади остаётся, «протыкание цели» пропадает.")
