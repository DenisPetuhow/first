def marks(D):
    """Пометки для автора, оставшиеся в документе. Вход: Doc. Отдаёт: число пометок «[ДАННЫЕ», «[МЕСТО», «[уточнить»."""
    texts = [p.text for p in D.d.paragraphs]         # текст абзацев
    for t in D.d.tables:                             # и ячеек таблиц
        texts += [c.text for row in t.rows for c in row.cells]
    return sum(s.count("[ДАННЫЕ") + s.count("[МЕСТО") + s.count("[уточнить") for s in texts)


