class Doc:
    """Документ со сквозной нумерацией рисунков, таблиц и формул. Вход: нет. Отдаёт: объект с методами разметки."""

    def __init__(self):
        self.d = Document()                          # документ python-docx
        self.fig, self.tab, self.frm = 0, 0, 0       # счётчики рисунков, таблиц, формул
        sec = self.d.sections[0]                     # единственный раздел
        sec.page_height, sec.page_width = Mm(297), Mm(210)
        sec.left_margin, sec.right_margin, sec.top_margin, sec.bottom_margin = Mm(30), Mm(15), Mm(20), Mm(20)
        st = self.d.styles["Normal"]                 # основной стиль
        st.font.name, st.font.size = "Times New Roman", Pt(14)
        st.element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
        pf = st.paragraph_format                     # абзац: по ширине, 1,5, отступ 1,25 см
        pf.alignment, pf.line_spacing, pf.first_line_indent = WD_ALIGN_PARAGRAPH.JUSTIFY, 1.5, Cm(1.25)
        pf.space_after, pf.space_before = Pt(0), Pt(0)
        self._page_numbers(sec)

    def _page_numbers(self, sec):
        """Номер страницы внизу по центру. Вход: раздел. Отдаёт: ничего."""
        p = sec.footer.paragraphs[0]                 # абзац нижнего колонтитула
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.first_line_indent = Cm(0)
        fld = OxmlElement("w:fldSimple"); fld.set(qn("w:instr"), "PAGE")   # поле PAGE — номер страницы
        r = OxmlElement("w:r"); t = OxmlElement("w:t"); t.text = "1"; r.append(t); fld.append(r)   # кусок текста поля: «1» до пересчёта в Word
        p._p.append(fld)

    def _runs(self, p, text, size=None, italic=False):
        """Текст с разметкой: **жирный**, `моноширинный`, [ДАННЫЕ…]/[МЕСТО…] — с подсветкой. Вход: абзац, текст. Отдаёт: ничего."""
        for part in re.split(r"(\*\*.+?\*\*|`.+?`|\[(?:ДАННЫЕ|МЕСТО|уточнить)[^\]]*\])", text):   # куски разметки
            if not part:                             # пустой кусок между метками
                continue
            if part.startswith("**"):                # жирный
                r = p.add_run(part[2:-2]); r.bold = True   # кусок жирного текста
            elif part.startswith("`"):               # имя из кода — моноширинным
                r = p.add_run(part[1:-1]); r.font.name = "Courier New"; r.font.size = Pt(12)
            elif part.startswith("["):               # пометка для автора — подсветить
                r = p.add_run(part); r.font.highlight_color = WD_COLOR_INDEX.YELLOW
            else:
                r = p.add_run(part)
            r.italic = italic or r.italic
            if size:                                 # свой кегль (таблицы)
                r.font.size = Pt(size)

    def h(self, text, level=1):
        """Заголовок раздела: полужирный, без точки, не отрывается от текста. Вход: текст, уровень. Отдаёт: ничего."""
        p = self.d.add_paragraph(); p.paragraph_format.keep_with_next = True   # абзац заголовка
        p.paragraph_format.space_before, p.paragraph_format.space_after = Pt(12), Pt(6)
        if level == 0:                               # заголовок документа — по центру
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER; p.paragraph_format.first_line_indent = Cm(0)
        r = p.add_run(text); r.bold = True   # текст заголовка

    def p(self, text, italic=False, center=False, indent=True):
        """Абзац основного текста. Вход: текст с разметкой, курсив, по центру, красная строка. Отдаёт: абзац."""
        par = self.d.add_paragraph()   # абзац основного текста
        if center:                                   # по центру, без отступа
            par.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if center or not indent:                     # без красной строки
            par.paragraph_format.first_line_indent = Cm(0)
        self._runs(par, text, italic=italic)
        return par

    def bullets(self, intro, items):
        """Список с вводной фразой: «— пункт;», последний — «.». Вход: вводная, пункты. Отдаёт: ничего."""
        if intro:                                    # вводная фраза с двоеточием
            self.p(intro)
        for i, it in enumerate(items):               # пункт за пунктом
            end = "." if i == len(items) - 1 else ";"   # знак конца пункта
            self.p("— " + it.rstrip(".;") + end)

    def numbered(self, intro, items):
        """Нумерованный перечень: «1) пункт;», последний — «.». Вход: вводная, пункты. Отдаёт: ничего."""
        if intro:                                    # вводная фраза с двоеточием
            self.p(intro)
        for i, it in enumerate(items):               # пункт за пунктом
            end = "." if i == len(items) - 1 else ";"   # знак конца пункта
            self.p("%d) %s%s" % (i + 1, it.rstrip(".;"), end))

    def spravochno(self, text):
        """Врезка «Справочно»: курсив, метка подчёркнута. Вход: текст. Отдаёт: ничего."""
        lab = self.d.add_paragraph(); r = lab.add_run("Справочно"); r.italic = True; r.underline = True   # метка «Справочно» и её текст
        lab.paragraph_format.left_indent = Cm(1.0)
        par = self.p(text, italic=True); par.paragraph_format.left_indent = Cm(1.0)   # сам текст врезки

    def table(self, title, head, rows, widths=None, size=12):
        """Таблица: подпись над, шапка жирная, сетка. Вход: название, шапка, строки, ширины см, кегль. Отдаёт: номер."""
        self.tab += 1
        cap = self.d.add_paragraph(); cap.paragraph_format.first_line_indent = Cm(0); cap.paragraph_format.keep_with_next = True   # подпись таблицы
        cap.add_run("Таблица %d — %s" % (self.tab, title))
        t = self.d.add_table(rows=1, cols=len(head)); t.style = "Table Grid"; t.alignment = WD_TABLE_ALIGNMENT.CENTER   # таблица с сеткой
        for j, hd in enumerate(head):                # шапка
            c = t.rows[0].cells[j]; c.paragraphs[0].paragraph_format.first_line_indent = Cm(0)   # ячейка шапки
            c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
            r = c.paragraphs[0].add_run(hd); r.bold = True; r.font.size = Pt(size)   # текст шапки
        for row in rows:                             # строки данных
            cells = t.add_row().cells                # ячейки строки
            for j, val in enumerate(row):            # ячейка за ячейкой
                par = cells[j].paragraphs[0]; par.paragraph_format.first_line_indent = Cm(0)   # абзац ячейки
                par.alignment = WD_ALIGN_PARAGRAPH.LEFT; par.paragraph_format.line_spacing = 1.0
                self._runs(par, str(val), size=size)
        if widths:                                   # ширины столбцов
            for row in t.rows:                       # каждая строка — те же ширины
                for j, w in enumerate(widths):       # столбец за столбцом
                    row.cells[j].width = Cm(w)
        self.d.add_paragraph().paragraph_format.space_after = Pt(0)
        return self.tab

    def figure(self, path, title, width_cm=16.0):
        """Рисунок по центру, подпись под ним. Вход: файл (нет — место для рисунка), название, ширина см. Отдаёт: номер."""
        self.fig += 1
        par = self.d.add_paragraph(); par.alignment = WD_ALIGN_PARAGRAPH.CENTER   # абзац рисунка
        par.paragraph_format.first_line_indent = Cm(0); par.paragraph_format.keep_with_next = True
        if path and os.path.exists(path):            # рисунок есть — вставить
            par.add_run().add_picture(path, width=Cm(width_cm))
        else:                                        # нет — место для автора
            self._runs(par, "[МЕСТО ДЛЯ РИСУНКА %d — %s]" % (self.fig, title))
        cap = self.p("Рисунок %d — %s" % (self.fig, title), center=True)   # подпись рисунка
        cap.paragraph_format.space_after = Pt(6)
        return self.fig

    def formula(self, text, where=None):
        """Формула в отдельной строке, номер справа в скобках, «где» — после. Вход: формула, пояснение. Отдаёт: номер."""
        self.frm += 1
        par = self.d.add_paragraph(); par.paragraph_format.first_line_indent = Cm(0)   # строка формулы
        ts = par.paragraph_format.tab_stops          # табуляции: центр и правый край
        ts.add_tab_stop(Cm(8.25), WD_TAB_ALIGNMENT.CENTER); ts.add_tab_stop(Cm(16.5), WD_TAB_ALIGNMENT.RIGHT)
        r = par.add_run("\t" + text); r.italic = True   # текст формулы курсивом
        par.add_run("\t(%d)" % self.frm)
        if where:                                    # пояснение символов
            self.p("где " + where, indent=False)
        return self.frm

    def page_break(self):
        """Разрыв страницы. Вход: нет. Отдаёт: ничего."""
        self.d.add_paragraph().add_run().add_break(WD_BREAK.PAGE)


def n(x, nd=1):
    """Число по ГОСТ-оформлению: запятая, неразрывные пробелы в разрядах. Вход: число, знаков. Отдаёт: строку."""
    s = ("%." + str(nd) + "f") % float(x)            # округлённое
    whole, _, frac = s.partition(".")                # целая и дробная части
    whole = re.sub(r"(?<=\d)(?=(\d{3})+$)", NB, whole)   # разряды
    return whole + ("," + frac if frac else "")


def src_size():
    """Объём исходного кода ПК. Вход: нет. Отдаёт: (число файлов .py в `src/`, число строк)."""
    files, lines = 0, 0                              # счётчики файлов и строк
    for top, _dirs, names in os.walk(os.path.join(ROOT, "src")):   # папка за папкой
        for nm in names:                             # файл за файлом
            if nm.endswith(".py"):                   # только исходные тексты
                files += 1
                with open(os.path.join(top, nm), encoding="utf-8", errors="replace") as f:
                    lines += sum(1 for _ in f)
    return files, lines


