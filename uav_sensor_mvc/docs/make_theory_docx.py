# -*- coding: utf-8 -*-
"""
Генератор Word-документа «Теория и математика решения».

Запуск:  python docs/make_theory_docx.py
Результат: docs/Теория_и_математика.docx

Документ написан так, чтобы в нём могли разобраться без специальной подготовки:
сначала суть метода простыми словами, затем — как он применяется в задаче.
Требуется пакет python-docx (pip install python-docx).
"""
import os
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

ACCENT = RGBColor(0x1F, 0x4E, 0x79)
MUTED = RGBColor(0x55, 0x55, 0x55)


def build():
    doc = Document()
    base = doc.styles["Normal"]
    base.font.name = "Calibri"
    base.font.size = Pt(11)

    def h(text, level=1):
        p = doc.add_heading(text, level=level)
        for r in p.runs:
            r.font.color.rgb = ACCENT
        return p

    def para(text="", bold=False, italic=False, size=None, color=None, align=None):
        p = doc.add_paragraph()
        r = p.add_run(text)
        r.bold = bold; r.italic = italic
        if size:
            r.font.size = Pt(size)
        if color:
            r.font.color.rgb = color
        if align:
            p.alignment = align
        return p

    def formula(text):
        p = doc.add_paragraph()
        p.paragraph_format.left_indent = Pt(24)
        r = p.add_run(text)
        r.italic = True
        r.font.name = "Consolas"
        r.font.size = Pt(11)
        return p

    def bullet(text, bold_head=None):
        p = doc.add_paragraph(style="List Bullet")
        if bold_head:
            p.add_run(bold_head + " ").bold = True
        p.add_run(text)
        return p

    # ------------------------------------------------------------------
    # Титул
    # ------------------------------------------------------------------
    t = doc.add_heading("Оптимальное размещение датчиков обнаружения БПЛА", level=0)
    for r in t.runs:
        r.font.color.rgb = ACCENT
    para("Теория и математика решения: подходы, алгоритмы, критерии и показатели",
         italic=True, color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)
    para("Документ объясняет, КАК решается задача и ПОЧЕМУ выбраны эти методы — "
         "понятным языком, с упором на жадный алгоритм оптимизации.",
         color=MUTED, align=WD_ALIGN_PARAGRAPH.CENTER)

    # ------------------------------------------------------------------
    h("1. Постановка задачи простыми словами", 1)
    para("Беспилотник (БПЛА) летит из точки A в точку B. У него ограниченный запас "
         "хода — он не может лететь сколь угодно длинным путём. Точный маршрут заранее "
         "неизвестен: каждый раз он немного другой (случайный). Наша задача — "
         "расставить N датчиков обнаружения (каждый «видит» в круге радиуса R) так, "
         "чтобы на типичном маршруте беспилотник был замечен:")
    bullet("не менее k раз (разными датчиками) — это называется КРАТНОСТЬ;", "•")
    bullet("равномерно вдоль всего пути, а не только в одном месте — РАВНОМЕРНОСТЬ.", "•")
    para("Поскольку маршрут случайный, мы не подгоняем датчики под один путь. Мы "
         "накапливаем много случайных маршрутов (выборку) и ищем расположение, которое "
         "в среднем хорошо по всей выборке. С ростом числа маршрутов расположение "
         "стабилизируется.")

    h("2. Геометрия: где вообще может лететь БПЛА", 1)
    para("Если суммарная длина пути не больше запаса хода L_max, то все достижимые "
         "точки лежат внутри ЭЛЛИПСА с фокусами A и B. Это «эллипс достижимости»:")
    formula("E = { P : |PA| + |PB| ≤ L_max }")
    para("Его большая полуось a = L_max/2 (наибольшее удаление вдоль линии A–B), "
         "межфокусное c = |AB|/2, малая полуось b = √(a² − c²). Любой маршрут длиной "
         "≤ L_max целиком лежит в этом эллипсе — значит запас хода автоматически "
         "удерживает БПЛА внутри, отдельная проверка не нужна.")
    para("На практике маршруты заполняют не весь эллипс, а более узкий «КОРИДОР "
         "ДВИЖЕНИЯ» между крайними возможными траекториями. Датчики имеет смысл "
         "ставить только в этом коридоре (вне его ни один маршрут не проходит), и "
         "карту удобнее масштабировать под коридор.")

    h("3. Модель движения беспилотника", 1)
    para("Этап 1 — ДУГИ. Маршрут — дуга от A до B, заданная углом отклонения θ "
         "(на сколько траектория «отклоняется» от прямой в точке старта):")
    bullet("θ = 0 — полёт по прямой A→B (самый короткий путь);", "•")
    bullet("чем больше θ, тем сильнее выгнута дуга и тем она длиннее;", "•")
    bullet("предельный угол θ_max — когда длина дуги равна запасу хода L_max "
           "(дальше отклоняться нельзя). Эти крайние дуги на карте — красный пунктир.", "•")
    para("Длина дуги связана с углом формулой L(θ) = c·θ / sin θ (растёт с θ). "
         "Случайный маршрут получается случайным выбором угла θ.")
    para("Профиль разброса задаёт, какие маршруты чаще:", bold=False)
    bullet("обычный — чаще короткие (угол около нуля);", "•")
    bullet("смешанный — поровну коротких и длинных;", "•")
    bullet("сложный — чаще сильно выгнутые (длинные обходные) маршруты.", "•")
    para("Этап 2 — ПЕТЛИ (петляющее движение): синусоида с закреплёнными концами "
         "A, B; амплитуда ограничена запасом хода. Метод решения при этом не меняется "
         "— меняется только генератор маршрутов.")

    h("4. Модель обнаружения", 1)
    para("Датчик засекает маршрут, если траектория хотя бы раз входит в его круг "
         "радиуса R. Повторные входы того же датчика не считаются. Поэтому число "
         "обнаружений n(S, γ) — это число РАЗНЫХ датчиков, засёкших маршрут γ при "
         "расположении S.")
    para("Отдельно считаем НЕПРЕРЫВНОЕ ПОКРЫТИЕ — какую долю длины пути беспилотник "
         "находится в зоне хотя бы одного датчика (это «процент сопровождения», он "
         "отличается от счёта засечек).")

    h("5. Критерии и показатели", 1)
    para("Важно различать КРИТЕРИИ (что оптимизируем) и ПОКАЗАТЕЛИ (что измеряем "
         "и докладываем).", bold=True)
    para("Критерии (входят в целевую функцию):", bold=True)
    bullet("кратность — не менее k засечек на маршрут;", "•")
    bullet("равномерность — засечки распределены вдоль всего пути.", "•")
    para("Показатели (рассчитываются по выборке для оценки качества):", bold=True)
    bullet("среднее число пересечений зон обнаружения 𝔼[n];", "•")
    bullet("средний процент пути под наблюдением (непрерывное покрытие);", "•")
    bullet("среднее расстояние, пройденное вне зон видимости;", "•")
    bullet("доля маршрутов, на которых выполнено требование ≥ k засечек;", "•")
    bullet("число фактически задействованных датчиков (равно N).", "•")

    h("6. Целевая функция (полезность расположения)", 1)
    para("Качество расположения S на одном маршруте γ выражает «полезность»:")
    formula("φ(S, γ) = α₁ · min(n, k)/k  +  α₂ · m/L_seg")
    para("Здесь n — число засёкших датчиков; min(n, k) «обрезает» сверх k (лишние "
         "засечки не вознаграждаются — ресурс лучше отдать необеспеченным маршрутам). "
         "m — число покрытых участков из L_seg (маршрут делится на L_seg равных "
         "отрезков; чем их больше, тем строже требование равномерности). Веса α₁, α₂ "
         "задают баланс: три режима — «пересечение» (0,75/0,25), «распределение» "
         "(0,25/0,75) и «сбалансированный» (0,5/0,5).")
    para("Истинная цель — максимизировать СРЕДНЮЮ полезность по всем возможным "
         "маршрутам (математическое ожидание):")
    formula("F(S) = 𝔼[φ(S, γ)] → max   при   |S| ≤ N")

    h("7. Метод оптимизации", 1)

    h("7.1. Что такое жадный алгоритм (суть)", 2)
    para("Жадный (greedy) алгоритм строит решение по шагам и на каждом шаге берёт то, "
         "что даёт НАИБОЛЬШУЮ сиюминутную выгоду, не пересматривая прошлые шаги.")
    para("Бытовая аналогия. Нужно расставить 6 камер так, чтобы покрыть как можно "
         "больше людей в торговом центре. Жадный способ: ставим первую камеру там, где "
         "она видит больше всего людей. Вторую — туда, где она добавит больше всего "
         "ЕЩЁ НЕ ОХВАЧЕННЫХ людей. И так далее, пока не расставим все 6. Каждый раз "
         "выбираем максимальную «прибавку».", italic=True)
    para("Именно так мы и ставим датчики: по одному, каждый раз выбирая позицию с "
         "наибольшим приростом средней полезности по накопленным маршрутам.")

    h("7.2. Почему жадный алгоритм здесь надёжен", 2)
    para("У нашей целевой функции есть два полезных свойства:")
    bullet("монотонность — добавление датчика не ухудшает результат;", "•")
    bullet("субмодулярность — «убывающая отдача»: чем больше датчиков уже стоит, тем "
           "меньше прибавка от следующего (как с камерами — первые дают много, "
           "последние мало).", "•")
    para("Для таких функций доказана теорема (Nemhauser, Wolsey, Fisher, 1978): "
         "жадный алгоритм гарантирует результат не хуже")
    formula("(1 − 1/e) ≈ 0,632  от наилучшего возможного.")
    para("То есть простой и быстрый жадный выбор даёт минимум 63 % от теоретического "
         "оптимума — а на практике обычно гораздо ближе к нему. Поэтому не нужны "
         "тяжёлые методы (полный перебор, метаэвристики).")

    h("7.3. Как жадный алгоритм применяется в задаче (по шагам)", 2)
    para("1) Область коридора покрывается СЕТКОЙ кандидатных позиций датчиков.")
    para("2) Заводится «структура покрытия»: для каждого кандидата и каждого "
         "накопленного маршрута заранее посчитано, засекает ли он маршрут и какие "
         "участки покрывает. Это позволяет считать прибавку очень быстро (векторно).")
    para("3) Пустое множество датчиков. Повторяем N раз:")
    bullet("для каждого свободного кандидата считаем прирост средней полезности "
           "F_t, если его добавить;", "  –")
    bullet("выбираем кандидата с максимальным приростом и фиксируем его;", "  –")
    para("4) Получаем N датчиков с гарантией (1 − 1/e).")
    para("Все N датчиков задействуются всегда: если основной критерий «насытился» "
         "(на маленькой выборке k засечек и покрытие достигаются малым числом "
         "датчиков), включается ВТОРИЧНЫЙ критерий — распределение оставшихся датчиков "
         "по плотности маршрутов. Так датчики не «застревают», а расходятся по самым "
         "частым путям.")

    h("7.4. Накопление выборки: метод выборочного среднего (SAA)", 2)
    para("Мы не знаем распределение маршрутов формулой — только через случайные "
         "примеры. Поэтому среднее по ВСЕМ маршрутам заменяем средним по НАКОПЛЕННОЙ "
         "выборке (Sample Average Approximation):")
    formula("F_t(S) = (1/t) · Σ φ(S, γᵢ),   i = 1..t")
    para("На каждой итерации добавляется новый маршрут, и расположение пересчитывается "
         "заново по всей выборке. С ростом t эмпирическое среднее сходится к истинному "
         "(закон больших чисел), и расположение стабилизируется.")
    para("Частый вопрос: «усредняются ли маршруты или координаты?» — НЕТ. Усредняется "
         "КРИТЕРИЙ (полезность). Координаты датчиков не осредняются: среднее двух "
         "хороших расположений может оказаться плохим. Число датчиков N фиксировано — "
         "оно не растёт с выборкой; растёт лишь точность оценки.", italic=True)

    # ------------------------------------------------------------------
    h("8. Сводка: что использовано", 1)
    table = doc.add_table(rows=1, cols=2)
    table.style = "Light Grid Accent 1"
    table.rows[0].cells[0].paragraphs[0].add_run("Элемент").bold = True
    table.rows[0].cells[1].paragraphs[0].add_run("Что использовано / как").bold = True
    rows = [
        ("Класс задачи", "Барьерное покрытие кратности k + равномерность; "
                         "стохастическая постановка (выборка маршрутов)."),
        ("Главный алгоритм", "Жадный субмодулярный выбор с гарантией (1 − 1/e)."),
        ("Метод по выборке", "Метод выборочного среднего (SAA), инкрементальный "
                             "пересчёт на каждой итерации."),
        ("Целевая функция", "φ = α₁·min(n,k)/k + α₂·m/L_seg (кратность + равномерность)."),
        ("Критерии", "Кратность (≥ k засечек) и равномерность (покрытие сегментов)."),
        ("Показатели", "Ср. пересечений, % пути под наблюдением, расстояние вне зон, "
                       "доля маршрутов ≥ k."),
        ("Геометрия", "Эллипс достижимости; коридор движения; дуги по углу θ, "
                      "предельный угол θ_max."),
        ("Дополнительно", "Вторичный критерий распределения (все N датчиков); "
                          "профили разброса маршрутов."),
    ]
    for a, b in rows:
        c = table.add_row().cells
        c[0].paragraphs[0].add_run(a).bold = True
        c[1].paragraphs[0].add_run(b)

    # ------------------------------------------------------------------
    h("9. Что НЕ применяли и почему", 1)
    bullet("Метаэвристику роя частиц (PSO) — по условию задачи на этом этапе не "
           "используется.", "•")
    bullet("Игровую постановку с «умным» противником (минимакс, Stackelberg, путь "
           "наименьшей экспозиции) — маршруты случайны и НЕ подстраиваются под "
           "датчики, рационального противника нет.", "•")
    bullet("Осреднение координат датчиков — недопустимо (среднее хороших решений "
           "бывает плохим). Усредняется критерий, а не координаты.", "•")

    h("10. Источники", 1)
    bullet("Nemhauser, Wolsey, Fisher (1978) — субмодулярная максимизация, "
           "гарантия (1 − 1/e).", "•")
    bullet("Kumar, Lai, Arora (2007) — барьерное покрытие кратности k.", "•")
    bullet("Church, ReVelle (1974) — задача максимального покрытия размещением "
           "(MCLP).", "•")
    bullet("Shapiro, Dentcheva, Ruszczyński — метод выборочного среднего (SAA).", "•")
    bullet("Robbins, Monro (1951) — стохастическая аппроксимация (для плавной "
           "динамики).", "•")

    out = os.path.join(os.path.dirname(__file__), "Теория_и_математика.docx")
    doc.save(out)
    print("Сохранено:", out)
    return out


if __name__ == "__main__":
    build()
