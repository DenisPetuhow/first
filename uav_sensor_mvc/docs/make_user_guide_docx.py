# -*- coding: utf-8 -*-
"""
Генератор Word-методички «Как пользоваться программой».

Запуск:  python docs/make_user_guide_docx.py
Результат: docs/Методичка_пользователя.docx

Документ для того, кто видит программу впервые: что нажимать, что означают режимы и
какие ограничения заложены в модель. Без формул и без подробностей реализации — только
то, что нужно, чтобы понимать, ПОЧЕМУ программа показывает именно это.
Требуется пакет python-docx (pip install python-docx).
"""
import os
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

ACCENT = RGBColor(0x1F, 0x4E, 0x79)
MUTED = RGBColor(0x55, 0x55, 0x55)


def _h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def _p(doc, text, italic=False, size=11):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.italic = italic
    run.font.size = Pt(size)
    if italic:
        run.font.color.rgb = MUTED
    return p


def _bullet(doc, text):
    return doc.add_paragraph(text, style="List Bullet")


def _num(doc, text):
    return doc.add_paragraph(text, style="List Number")


def _table(doc, rows, widths=None):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Light Grid Accent 1"
    for r in rows:
        cells = t.add_row().cells
        for i, val in enumerate(r):
            cells[i].text = str(val)
    return t


def build():
    doc = Document()
    base = doc.styles["Normal"]
    base.font.name = "Calibri"
    base.font.size = Pt(11)

    # ── титул ─────────────────────────────────────────────────────────────────
    title = doc.add_heading("Карта угроз: размещение датчиков обнаружения БПЛА", level=0)
    for run in title.runs:
        run.font.color.rgb = ACCENT
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("Методичка пользователя — что нажимать и как понимать результат")
    run.italic = True
    run.font.color.rgb = MUTED

    _h(doc, "О чём программа", 1)
    _p(doc, "Задача: определить расположение датчиков обнаружения, обеспечивающее засечку "
            "беспилотных аппаратов при минимальном числе датчиков. Решение рассчитывается "
            "численно по данным реальной местности.")
    _p(doc, "Логика в трёх шагах:")
    _num(doc, "По цифровой карте (реки, дороги, ЛЭП, застройка, высоты) строится "
              "ВЕСОВАЯ КАРТА: пригодность каждого участка местности для полёта.")
    _num(doc, "По ней прокладывается множество вероятных маршрутов — не одна линия, а выборка: "
              "траектория аппарата заранее неизвестна.")
    _num(doc, "Датчики размещаются в позициях, через которые проходит наибольшее число маршрутов.")
    _p(doc, "Выборка используется потому, что траектория неизвестна: рассчитывается множество "
            "возможных путей, и расстановка выполняется по наиболее частым из них.",
       italic=True)

    # ── порядок работы ────────────────────────────────────────────────────────
    _h(doc, "1. Порядок работы", 1)
    _num(doc, "«Построить карту» — слои накладываются на сетку 500 м, рассчитывается вес ячеек.")
    _num(doc, "«Добавить рельеф» — карта пересобирается с учётом высот. Пересборка сбрасывает "
              "маршруты и датчики: они рассчитаны по прежней карте.")
    _num(doc, "«Указать цель» — задаётся щелчком по карте. Точка вылета фиксирована.")
    _num(doc, "«Пуск» / «Шаг» / «Пакетно» — накопить маршруты. «Пуск» отображает движение аппарата, "
              "«Пакетно» рассчитывает всю выборку сразу.")
    _num(doc, "«Расставить датчики» — размещение N датчиков по накопленной выборке маршрутов.")
    _p(doc, "«Применить» — пересчёт после изменения параметров. «Сброс» — удаление датчиков, "
            "цели и запретных зон; карта сохраняется.")

    # ── кнопки ────────────────────────────────────────────────────────────────
    _h(doc, "2. Кнопки", 1)
    _table(doc, [
        ("Кнопка", "Что делает"),
        ("Справка", "настоящее руководство в интерфейсе программы"),
        ("Входные данные…", "запас хода, скорость, крен, длина прямого участка"),
        ("Выбрать цифровые карты…", "источник данных и состав слоёв, влияющих на вес ячеек "
                                    "(требуется пересборка карты)"),
        ("Векторные слои…", "выбор слоёв для отображения; пересчёт не выполняется"),
        ("Запретная зона", "построение области, в которой пролёт невозможен: щелчки задают "
                           "вершины, колёсико замыкает контур, Esc отменяет"),
        ("Убрать зону", "удаление последней зоны; все зоны удаляются кнопкой «Сброс»"),
        ("Весь участок", "возврат к полному виду участка"),
    ])

    # ── режимы ────────────────────────────────────────────────────────────────
    _h(doc, "3. Режимы", 1)
    _table(doc, [
        ("Режим", "Смысл"),
        ("Приоритет по весу", "максимальный — маршрут стремится к коридорам с высоким "
                              "весом; минимальный — к участкам с низким весом; смесь — режим "
                              "выбирается для каждого маршрута"),
        ("Разброс по карте", "удаление маршрута от прямой вход—цель: центр / середина / "
                             "края / смесь. Разброс определяет покрытие области выборкой"),
        ("Расход запаса", "запас израсходуется в начале маршрута, ближе к цели либо равномерно"),
        ("Режим оптимизации", "критерий расстановки: покрытие, стоимость или их баланс"),
    ])

    # ── ограничения ───────────────────────────────────────────────────────────
    _h(doc, "4. Ограничения, заложенные в модель", 1)
    _p(doc, "Перечисленное не относится к настраиваемым параметрам: это правила, без которых результат расчёта не соответствовал бы действительности.")

    _h(doc, "Города и застройка", 2)
    _bullet(doc, "Над городом полёт исключён: территория населённого пункта не входит в область пролёта.")
    _bullet(doc, "Сельский населённый пункт полёт не исключает, но вес снижается к его центру, вследствие чего маршрут проходит по окраине.")
    _bullet(doc, "Русло реки, проходящее через небольшой населённый пункт, остаётся коридором; в границах крупного города оно закрывается вместе с ним.")
    _bullet(doc, "Тип населённого пункта определяется по данным участка (площадь застройки и компактность), а не по метке цифровой карты, поскольку метки неоднородны.")

    _h(doc, "Рельеф", 2)
    _bullet(doc, "Высоты влияют на вес: та же дорога в низине получает больший вес, чем на гребне, так как в низине аппарат менее заметен.")
    _bullet(doc, "Возвышенность выше порогового значения исключает коридор полностью.")
    _bullet(doc, "Рельеф учитывается дважды: в весе карты и в стоимости прохода. Иначе возвышенности не влияли бы на выбор маршрута.")
    _bullet(doc, "Учёт рельефа включается отдельной кнопкой и требует пересборки карты.")

    _h(doc, "Датчики", 2)
    _bullet(doc, "Не размещаются на воде, включая буфер 250 м.")
    _bullet(doc, "В границах населённого пункта и в запретной зоне размещение допускается: они ограничивают полёт, а не наблюдение.")
    _bullet(doc, "Выдерживается разнос между позициями.")
    _bullet(doc, "Размещение выполняется по частоте пролёта, а не по весу карты.")

    _h(doc, "Движение БПЛА", 2)
    _bullet(doc, "Длина маршрута не превышает запас хода, маршрут не выходит за область залёта.")
    _bullet(doc, "Для аппарата самолётного типа задан минимальный радиус разворота: при скорости 180 км/ч и крене 25° он составляет около 550 м. Разворот на месте исключён.")
    _bullet(doc, "В зоне подхода (10 км от цели) маршрут только сближается с целью. Заход с противоположного направления допускается, но выполняется обходом.")
    _bullet(doc, "Запретная зона сужает область пролёта — таково её назначение. Зона, перекрывающая коридор, может сделать цель недостижимой; программа выводит соответствующее сообщение.")

    # ── влияние параметров ────────────────────────────────────────────────────
    _h(doc, "5. Влияние параметров на результат", 1)

    _h(doc, "Расстановка датчиков", 2)
    _table(doc, [
        ("Параметр", "Влияние"),
        ("N — число датчиков", "чем меньше значение, тем выше значимость каждой позиции"),
        ("R — радиус обнаружения", "больший радиус повышает засечку; при большом R влияние прочих настроек снижается"),
        ("k — кратность засечки", "число датчиков, которые должны обнаружить аппарат; увеличение k приводит к более плотному размещению"),
        ("Шаг сетки датчиков", "шаг перебора возможных позиций. Определяется автоматически как половина радиуса. При шаге, превышающем радиус, между позициями остаются промежутки шире зоны обзора"),
    ])

    _h(doc, "Движение аппарата", 2)
    _table(doc, [
        ("Параметр", "Влияние"),
        ("Запас хода", "увеличение расширяет разброс маршрутов и повышает число манёвров вблизи цели"),
        ("Разрыв между секторами", "предельная протяжённость участка без ориентиров, пересекаемого между коридорами"),
        ("Уход от ориентира", "допустимое боковое отклонение от реки или дороги"),
        ("Длина прямого участка", "протяжённость удержания курса до доворота"),
        ("Скорость и крен", "определяют радиус разворота и манёвренность аппарата"),
    ])

    # ── слои ──────────────────────────────────────────────────────────────────
    _h(doc, "6. Отображаемые слои", 1)
    _table(doc, [
        ("Слой", "Что означает"),
        ("Весовая карта", "пригодность местности для полёта"),
        ("Зона пролёта", "все участки, достижимые в пределах запаса хода"),
        ("Маршруты движения", "накопленная выборка путей"),
        ("Тепловая карта маршрутов", "частота пролёта над ячейкой; расстановка датчиков выполняется по ней"),
        ("Приоритет высот", "результат учёта рельефа в весе: синим — укрытия, красным — возвышенности, чёрным — исключённые коридоры"),
        ("Запретные зоны", "области, в которых пролёт невозможен"),
    ])
    _p(doc, "Отметка слоя управляет только отображением и не влияет на расчёт. Ползунок под группой задаёт прозрачность. Слой, который ещё не рассчитан, отображается неактивным.")

    _p(doc, "Демонстрационная сборка не требует подключения к сети: карта-подложка берётся из локального кэша, расчёты выполняются на месте.", italic=True)

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "Методичка_пользователя.docx")
    doc.save(out)
    return out


if __name__ == "__main__":
    print("сохранено:", build())
