# -*- coding: utf-8 -*-
"""
Генератор Word-методички «Как пользоваться программой».

Запуск:  python docs/make_user_guide_docx.py
Результат: docs/Методичка_пользователя.docx

Документ для того, кто видит программу впервые: что нажимать, что означают режимы и
какие ограничения заложены в модель. Без формул и без подробностей реализации — только
то, что нужно, чтобы понимать, ПОЧЕМУ программа показывает именно это.
Требуется пакет python-docx (pip install python-docx).

Обновлено 06.09.2026 под сборку с четырьмя типами датчиков, окном «Исходные данные»,
историей полётов, анализом размещения, режимом анализа, линейкой «Расстояние» и
анализом моделирования по 12 направлениям компаса — см. теория/сборка/
РУКОВОДСТВО_ПОЛЬЗОВАТЕЛЯ.md (тот же материал, в формате markdown, с оглавлением).
"""
import os
from docx import Document
from docx.shared import Pt, RGBColor
from docx.enum.text import WD_ALIGN_PARAGRAPH

ACCENT = RGBColor(0x1F, 0x4E, 0x79)
MUTED = RGBColor(0x55, 0x55, 0x55)


def _h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.color.rgb = ACCENT
    return p


def _p(doc, text, italic=False, size=11):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.italic = italic
    run.font.size = Pt(size)
    if italic:
        run.font.color.rgb = MUTED
    return p


def _bullet(doc, text):
    return doc.add_paragraph(text, style="List Bullet")


def _num(doc, text):
    return doc.add_paragraph(text, style="List Number")


def _table(doc, rows, widths=None):
    t = doc.add_table(rows=0, cols=len(rows[0]))
    t.style = "Light Grid Accent 1"
    for r in rows:
        cells = t.add_row().cells
        for i, val in enumerate(r):
            cells[i].text = str(val)
    return t


def build():
    doc = Document()
    base = doc.styles["Normal"]
    base.font.name = "Calibri"
    base.font.size = Pt(11)

    # ── титул ─────────────────────────────────────────────────────────────────
    title = doc.add_heading("Карта угроз: размещение датчиков обнаружения БПЛА", level=0)
    for run in title.runs:
        run.font.color.rgb = ACCENT
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run("Методичка пользователя — что нажимать и как понимать результат")
    run.italic = True
    run.font.color.rgb = MUTED

    _h(doc, "О чём программа", 1)
    _p(doc, "Задача: определить расположение датчиков обнаружения, обеспечивающее засечку "
            "беспилотных аппаратов при минимальном числе датчиков. Ни точка появления "
            "аппарата, ни его точный маршрут заранее не известны — известна местность и "
            "охраняемая цель. Решение рассчитывается численно по данным реальной местности.")
    _p(doc, "Логика в трёх шагах:")
    _num(doc, "По цифровой карте (реки, дороги, ЛЭП, застройка, высоты) строится "
              "ВЕСОВАЯ КАРТА: пригодность каждого участка местности для полёта.")
    _num(doc, "По ней прокладывается множество вероятных маршрутов — не одна линия, а выборка: "
              "траектория аппарата заранее неизвестна.")
    _num(doc, "Датчики размещаются в позициях, через которые проходит наибольшее число "
              "маршрутов, — либо задаются вручную, если обстановка известна заранее.")
    _p(doc, "Выборка используется потому, что траектория неизвестна: рассчитывается множество "
            "возможных путей, и расстановка выполняется по наиболее частым из них.",
       italic=True)

    # ── порядок работы ────────────────────────────────────────────────────────
    _h(doc, "1. Порядок работы", 1)
    _num(doc, "«Построить карту» — слои накладываются на сетку 500 м, рассчитывается вес ячеек.")
    _num(doc, "«Добавить рельеф» — карта пересобирается с учётом высот. Пересборка сбрасывает "
              "маршруты и датчики: они рассчитаны по прежней карте.")
    _num(doc, "«Указать цель» — задаётся щелчком по карте.")
    _num(doc, "«Задать сектор» — щелчок по краю карты задаёт направление, откуда может "
              "появиться аппарат: от цели к указанной точке проводится ось, от неё "
              "откладывается по 30° в каждую сторону. На попавшем в сектор крае "
              "отбираются пять точек входа.")
    _num(doc, "«Применить» — только теперь считаются маршруты; предыдущие щелчки лишь "
              "задавали обстановку.")
    _num(doc, "«Пуск» / «Шаг» / «Пакетно» — накопить маршруты. «Пуск» отображает движение "
              "аппарата, «Пакетно» рассчитывает всю выборку сразу.")
    _num(doc, "«Расставить датчики» либо окно «Исходные данные» → «Задать позиции» — "
              "размещение датчиков алгоритмом или вручную (раздел 4).")
    _p(doc, "«Сброс» — удаление датчиков, цели, сектора и запретных зон; карта сохраняется. "
            "«Очистить» — возврат расстановки к состоянию до моделирования, без потери "
            "заданных датчиков. «Очистить датчики» — удаление ВСЕЙ расстановки с карты.")

    # ── кнопки ────────────────────────────────────────────────────────────────
    _h(doc, "2. Кнопки и окна", 1)
    _table(doc, [
        ("Кнопка / окно", "Что делает"),
        ("Исходные данные…", "одно окно: запас хода, скорость, крен, кратность засечки, "
                             "число и радиус каждого из четырёх типов датчиков, "
                             "переключатель «Рассчитать позиции» / «Задать позиции», "
                             "таблица уже поставленных датчиков"),
        ("Выбрать цифровые карты…", "источник данных и состав слоёв, влияющих на вес ячеек "
                                    "(требуется пересборка карты)"),
        ("Векторные слои…", "выбор слоёв для отображения; пересчёт не выполняется"),
        ("Задать сектор / Убрать", "направление появления аппарата и его отмена"),
        ("Запретная зона", "построение области, в которой пролёт невозможен: щелчки задают "
                           "вершины, колёсико замыкает контур, Esc отменяет"),
        ("Убрать зону", "удаление последней зоны; все зоны удаляются кнопкой «Сброс»"),
        ("Добавить датчик", "постановка датчика двойным щелчком по карте; правая кнопка "
                            "мыши или Esc — выход из режима"),
        ("Редактировать датчики", "щелчок выбирает ближайший датчик, перетаскивание "
                                  "переносит его, Delete удаляет"),
        ("Очистить датчики", "удаление с карты всей расстановки — и подобранной, и "
                             "заданной вручную"),
        ("Анализ моделирования", "окно с полной статистикой засечки одним снимком "
                                 "(раздел 5)"),
        ("Выгрузить / Загрузить / Удалить историю полётов", "сохранить накопленные "
         "маршруты в файл, подгрузить чужой файл как выборку для расстановки, убрать "
         "загруженную выборку"),
        ("Весь участок", "возврат к полному виду участка"),
        ("«Расстояние» (плашка над картой)", "измерение по карте: клик — точка, между "
         "соседними — отрезок с длиной, у последней точки — сумма всей цепочки"),
    ])

    # ── режимы ────────────────────────────────────────────────────────────────
    _h(doc, "3. Режимы", 1)
    _table(doc, [
        ("Режим", "Смысл"),
        ("Приоритет по весу", "максимальный — маршрут стремится к коридорам с высоким "
                              "весом; минимальный — к участкам с низким весом; смесь — режим "
                              "выбирается для каждого маршрута"),
        ("Разброс по карте", "удаление маршрута от прямой вход—цель: центр / середина / "
                             "края / смесь. Разброс определяет покрытие области выборкой"),
        ("Расход запаса", "запас израсходуется в начале маршрута, ближе к цели либо равномерно"),
        ("Режим оптимизации", "критерий расстановки: покрытие, стоимость или их баланс"),
        ("«режим анализа» (плашка над картой)", "во время моделирования расстановка не "
         "пересчитывается — держит датчики на месте, чтобы честно сравнить состояние "
         "«до» и «после» (раздел 5). Включать до начала моделирования"),
    ])

    # ── датчики: типы и расстановка ───────────────────────────────────────────
    _h(doc, "4. Датчики: четыре типа и два способа расстановки", 1)
    _p(doc, "Типы 1–3 (малые) перехватывают пролёт вдоль коридоров: у каждого свой радиус "
            "и своя кратность засечки. Тип 4 (большие) обеспечивает круговое наблюдение "
            "вокруг цели: кольцо делится на равные доли, в каждой один датчик. Число "
            "датчиков типа 4, равное нулю, означает, что кольцевой щит не строится.")
    _h(doc, "Способы расстановки (переключатель в окне «Исходные данные»)", 2)
    _bullet(doc, "«Рассчитать позиции» — датчики подбирает алгоритм; таблица показывает "
                "результат. Часть датчиков можно закрепить вручную — остальные алгоритм "
                "доберёт вокруг них.")
    _bullet(doc, "«Задать позиции» — датчики стоят ровно там, где их поставил человек; "
                "алгоритм не подбирает ничего, только считает показатели по заданным местам.")
    _h(doc, "Статический и динамический режим датчика", 2)
    _p(doc, "Выбирается при постановке каждого датчика. Статический не двигается никогда. "
            "Динамический во время моделирования может быть переставлен алгоритмом, если "
            "так лучше для покрытия; до начала моделирования оба стоят там, где заданы.")
    _p(doc, "Зоны датчиков типа 4 слегка перекрываются, и это правильно: чтобы они совсем "
            "не пересекались, их пришлось бы развести дальше радиуса обзора, и тогда цель "
            "осталась бы вне наблюдения.", italic=True)

    # ── анализ и статистика ───────────────────────────────────────────────────
    _h(doc, "5. Анализ и статистика", 1)
    _p(doc, "Под картой выводится основной показатель — засечка ≥ k: доля маршрутов "
            "выборки, обнаруженных не менее чем k разными датчиками. Значение 1.000 "
            "означает, что все маршруты выборки надёжно перехватываются.")
    _h(doc, "Кнопка «Анализ моделирования»", 2)
    _p(doc, "Открывает окно с полной статистикой засечки на момент нажатия: сумма (с "
            "количеством и процентом), то же самое отдельно по каждому из четырёх типов "
            "датчиков вместе с долей покрытия веса именно этим типом, и разбивка по 12 "
            "направлениям компаса вокруг цели — с какой стороны сколько маршрутов пришло "
            "и скольким из них хватило кратности. Направления, которым не хватило, "
            "отмечаются отдельно; те же 12 направлений видны на карте — 12 лучей от цели, "
            "включаются галкой «Сектора».")
    _h(doc, "Галка «Анализ размещения»", 2)
    _p(doc, "Сравнивает первое построение расстановки с текущим: серый круг — где датчик "
            "стоял изначально, стрелка — куда он переехал, подпись — на сколько "
            "километров. Отсутствие стрелки означает, что датчик стоит там же, где встал "
            "первым.")
    _p(doc, "Чтобы это сравнение было показательным, а не смазанным обычным пересчётом "
            "расстановки по ходу моделирования, перед началом моделирования включается "
            "«режим анализа» (раздел 3) — расстановка тогда замирает, как только "
            "что-то уже поставлено.", italic=True)
    _h(doc, "История полётов", 2)
    _p(doc, "Накопленные маршруты можно выгрузить в файл и позже загрузить как выборку "
            "для расстановки датчиков — до начала собственных итераций. Список пройденных "
            "и загруженных маршрутов с подсветкой на карте открывается кнопкой «Посмотреть "
            "маршруты» в окне «Исходные данные».")

    # ── ограничения ───────────────────────────────────────────────────────────
    _h(doc, "6. Ограничения, заложенные в модель", 1)
    _p(doc, "Перечисленное не относится к настраиваемым параметрам: это правила, без которых результат расчёта не соответствовал бы действительности.")

    _h(doc, "Города и застройка", 2)
    _bullet(doc, "Над городом полёт исключён: территория населённого пункта не входит в область пролёта.")
    _bullet(doc, "Сельский населённый пункт полёт не исключает, но вес снижается к его центру, вследствие чего маршрут проходит по окраине.")
    _bullet(doc, "Русло реки, проходящее через небольшой населённый пункт, остаётся коридором; в границах крупного города оно закрывается вместе с ним.")
    _bullet(doc, "Тип населённого пункта определяется по данным участка (площадь застройки и компактность), а не по метке цифровой карты, поскольку метки неоднородны.")

    _h(doc, "Рельеф", 2)
    _bullet(doc, "Высоты влияют на вес: та же дорога в низине получает больший вес, чем на гребне, так как в низине аппарат менее заметен.")
    _bullet(doc, "Возвышенность выше порогового значения исключает коридор полностью.")
    _bullet(doc, "Рельеф учитывается дважды: в весе карты и в стоимости прохода. Иначе возвышенности не влияли бы на выбор маршрута.")
    _bullet(doc, "Учёт рельефа включается отдельной кнопкой и требует пересборки карты.")

    _h(doc, "Датчики", 2)
    _bullet(doc, "Не размещаются на воде, включая буфер 250 м.")
    _bullet(doc, "В границах населённого пункта и в запретной зоне размещение допускается: они ограничивают полёт, а не наблюдение.")
    _bullet(doc, "Выдерживается разнос между позициями — свой внутри каждого типа, свой между разными типами.")
    _bullet(doc, "Размещение выполняется по частоте пролёта, а не по весу карты.")

    _h(doc, "Движение БПЛА", 2)
    _bullet(doc, "Длина маршрута не превышает запас хода, маршрут не выходит за область залёта.")
    _bullet(doc, "Для аппарата самолётного типа задан минимальный радиус разворота: при скорости 180 км/ч и крене 25° он составляет около 550 м. Разворот на месте исключён.")
    _bullet(doc, "В зоне подхода (10 км от цели) маршрут только сближается с целью. Заход с противоположного направления допускается, но выполняется обходом.")
    _bullet(doc, "Запретная зона сужает область пролёта — таково её назначение. Зона, перекрывающая коридор, может сделать цель недостижимой; программа выводит соответствующее сообщение.")

    # ── влияние параметров ────────────────────────────────────────────────────
    _h(doc, "7. Влияние параметров на результат", 1)

    _h(doc, "Расстановка датчиков", 2)
    _table(doc, [
        ("Параметр", "Влияние"),
        ("N — число датчиков", "чем меньше значение, тем выше значимость каждой позиции"),
        ("R — радиус обнаружения", "больший радиус повышает засечку; при большом R влияние прочих настроек снижается"),
        ("k — кратность засечки", "число датчиков, которые должны обнаружить аппарат; увеличение k приводит к более плотному размещению"),
        ("Шаг сетки датчиков", "шаг перебора возможных позиций. Определяется автоматически как половина радиуса. При шаге, превышающем радиус, между позициями остаются промежутки шире зоны обзора"),
    ])

    _h(doc, "Движение аппарата", 2)
    _table(doc, [
        ("Параметр", "Влияние"),
        ("Запас хода", "увеличение расширяет разброс маршрутов и повышает число манёвров вблизи цели"),
        ("Разрыв между секторами", "предельная протяжённость участка без ориентиров, пересекаемого между коридорами"),
        ("Уход от ориентира", "допустимое боковое отклонение от реки или дороги"),
        ("Длина прямого участка", "протяжённость удержания курса до доворота"),
        ("Скорость и крен", "определяют радиус разворота и манёвренность аппарата"),
    ])

    # ── слои ──────────────────────────────────────────────────────────────────
    _h(doc, "8. Отображаемые слои", 1)
    _table(doc, [
        ("Слой", "Что означает"),
        ("Весовая карта", "пригодность местности для полёта"),
        ("Зона пролёта", "все участки, достижимые в пределах запаса хода"),
        ("Маршруты движения", "накопленная выборка путей"),
        ("Тепловая карта маршрутов", "частота пролёта над ячейкой; расстановка датчиков выполняется по ней"),
        ("Приоритет высот", "результат учёта рельефа в весе: синим — укрытия, красным — возвышенности, чёрным — исключённые коридоры"),
        ("Запретные зоны", "области, в которых пролёт невозможен"),
        ("Анализ размещения", "серый круг и стрелка: позиция первого построения и куда датчик переехал к текущему моменту"),
        ("Сектора", "12 лучей от цели по направлениям компаса; красным — направления, не набравшие заданную кратность"),
    ])
    _p(doc, "Отметка слоя управляет только отображением и не влияет на расчёт. Ползунок под группой задаёт прозрачность. Слой, который ещё не рассчитан, отображается неактивным.")

    _p(doc, "Сборка для показа не требует подключения к сети: карта-подложка берётся из локального кэша, расчёты выполняются на месте.", italic=True)

    out = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                       "Методичка_пользователя.docx")
    doc.save(out)
    return out


